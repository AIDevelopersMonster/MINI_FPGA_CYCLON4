// =======================================================
// Project    : MINI_FPGA_CYCLONE4
// Module     : Jitter_Elimination_module
// Function   : Устранение дребезга кнопки + формирование
//              однократного импульса на фронт/спад входа.
//
// Description:
//   Модуль отслеживает переход Button_In из 1 → 0.
//   На один такт формируется импульс Button_Out = 1.
//   Это используется для надёжного считывания кнопок
//   (устранение дребезга + edge-detect).
//
// Ports:
//   CLK        – системный такт FPGA
//   RSTn       – асинхронный сброс (активный ноль)
//   Button_In  – "сырая" кнопка
//   Button_Out – однократный импульс при переходе 1 → 0
//
// Принцип работы:
//   neg1 ← текущее состояние кнопки
//   neg2 ← состояние кнопки на предыдущем такте
//   Если neg2 = 1 и neg1 = 0 → выявлен спад → выдаём импульс
// =======================================================

module Jitter_Elimination_module
(
	CLK,
	RSTn,
	Button_In,
	Button_Out
); 		

	 input CLK;          // Системный тактовый сигнал
	 input RSTn;         // Асинхронный сброс (активный 0)
	 input Button_In;    // Сырая кнопка
	 output Button_Out;  // Однократный импульс при 1→0

	 reg neg1;           // Текущее состояние кнопки (задержка 1 такт)
	 reg neg2;           // Предыдущее состояние кнопки
	
	// ----------------------------------------------------
	// Двухтактный регистратор для подавления дребезга
	// ----------------------------------------------------
	always @ ( posedge CLK or negedge RSTn )
		if( !RSTn )
			begin
				neg1 <= 1'b1;
				neg2 <= 1'b1;			
			end
		else 
			begin
				neg1 <= Button_In;  // Текущая выборка
				neg2 <= neg1;       // Предыдущая выборка
			end

	// ----------------------------------------------------
	// Детектор спада: выдаёт 1, если было 1 → стало 0
	// ----------------------------------------------------
	assign Button_Out = ( neg2 & (!neg1) ) ? 1'b1 : 1'b0;

endmodule
