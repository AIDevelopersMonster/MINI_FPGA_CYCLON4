// =======================================================
// Project    : MINI_FPGA_CYCLONE4
// Module     : dac_module
// Function   : Простой интерфейс вывода данных DDS в ЦАП
// Device     : Cyclone IV
// -------------------------------------------------------
// Описание:
//   Модуль является выходным звеном DDS. Он:
//     1) Передает входные 8-битные данные Wave_Data в DA_Data_Out
//        без задержек и обработки.
//     2) Пробрасывает тактовый сигнал CLK дальше как DA_CLK
//        — внешний ЦАП или DA-плата синхронизирует обновление
//        данных по этому такту.
//   Таким образом, частота вывода  = частоте системного такта CLK.
//
// Порты:
//   CLK          – системный такт FPGA (выдается на ЦАП как DA_CLK).
//   Wave_Data    – 8-битные выборки формы волны (синус, квадрат, пила).
//   DA_CLK       – тактовый сигнал для внешнего ЦАП/DA-board.
//   DA_Data_Out  – данные, подаваемые в ЦАП.
// -------------------------------------------------------
// Модуль минимален, т.к. вся логика формирования волны находится
// в choose_wave_module и ROM-модулях DDS.
// =======================================================

module dac_module
(
	CLK,
	Wave_Data,
	DA_CLK,
	DA_Data_Out
);

   input CLK;                 // Системный такт
	input [7:0]Wave_Data;     // Входные данные от DDS
   output DA_CLK;             // Тактовый сигнал для ЦАП
   output [7:0]DA_Data_Out;   // Цифровые выходные данные в ЦАП

	// ---------------------------------------------------
	// DA_CLK = CLK — прямое пробрасывание такта в ЦАП
	// ---------------------------------------------------
   assign DA_CLK = CLK;		

	// ---------------------------------------------------
	// Передача данных в ЦАП без изменений
	// ---------------------------------------------------
	assign DA_Data_Out = Wave_Data;

endmodule
