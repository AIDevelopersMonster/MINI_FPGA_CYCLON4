// =======================================================
// Project    : MINI_FPGA_CYCLONE4
// Module     : frequency_adjust_module
// Function   : Формирование управляющего слова частоты (KW)
//              по нажатию двух кнопок: "увеличить" и "уменьшить".
// Device     : Cyclone IV
// -------------------------------------------------------
// Описание:
//   - На вход подаются два сигнала от кнопок: KW_Add_In и KW_Sub_In.
//   - Каждая кнопка пропускается через модуль подавления дребезга
//     Jitter_Elimination_module, на выходе которого формируется
//     однократный импульс KW_Add_Sig / KW_Sub_Sig.
//   - Внутренний регистр KWr изменяется в диапазоне 1..10 с циклическим
//     переходом (1 ←→ 10):
//       * при нажатии "плюс":  1→2→3→...→10→1→...
//       * при нажатии "минус":10→9→...→1→10→...
//   - Начальное значение KWr = 5 при сбросе.
// -------------------------------------------------------
// Порты:
//   CLK        – системный тактовый сигнал
//   RSTn       – асинхронный сброс (активный 0)
//   KW_Add_In  – кнопка "увеличить частоту"
//   KW_Sub_In  – кнопка "уменьшить частоту"
//   KW[11:0]   – управляющее слово частоты для DDS
// =======================================================

module frequency_adjust_module
(
	CLK,
	RSTn,
	KW_Add_In,
	KW_Sub_In,
	KW
);

	 input CLK;
	 input RSTn;
	 input KW_Add_In;    // "Плюс" – увеличить KW
	 input KW_Sub_In;    // "Минус" – уменьшить KW
	 output [11:0]KW;    // frequency control words
	 
	 // Однократные импульсы после подавления дребезга
	 wire KW_Add_Sig;
	 wire KW_Sub_Sig;

	 // Внутренний регистр управляющего слова частоты
	 reg [11:0]KWr;
	 
	// ---------------------------------------------------
	// Подавление дребезга и детекция нажатия кнопки "плюс"
	// ---------------------------------------------------
	Jitter_Elimination_module U1
	(
		.CLK       ( CLK        ),
		.RSTn      ( RSTn       ),
		.Button_In ( KW_Add_In  ),	// input - from top
		.Button_Out( KW_Add_Sig ) 	// output - к логике изменения KWr
	);
	 
 	// ---------------------------------------------------
	// Подавление дребезга и детекция нажатия кнопки "минус"
	// ---------------------------------------------------
 	Jitter_Elimination_module U2
	(
		.CLK       ( CLK        ),
		.RSTn      ( RSTn       ),
		.Button_In ( KW_Sub_In  ),	// input - from top
		.Button_Out( KW_Sub_Sig ) 	// output - к логике изменения KWr
	);
	
	// ---------------------------------------------------
	// Логика изменения управляющего слова частоты KWr
	// Диапазон: 1..10, циклический переход, сброс = 5
	// ---------------------------------------------------
	always @ ( posedge CLK or negedge RSTn )
		begin
			if( !RSTn ) 
				KWr <= 12'd5;              // Стартовое значение частоты
			else if( KW_Add_Sig == 1 )
				// При достижении максимума 10 → переход к 1
				if ( KWr == 12'd10 )
					KWr <= 12'd1;
				else 
					KWr <= KWr + 12'd1;
			else if( KW_Sub_Sig == 1 )
				// При достижении минимума 1 → переход к 10
				if ( KWr == 12'd1 )
					KWr <= 12'd10;
				else 
					KWr <= KWr - 12'd1;
		end
		
	// Вывод управляющего слова
	assign KW = KWr;
	
endmodule
