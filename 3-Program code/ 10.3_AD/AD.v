//=============================================================
// Модуль: AD
// Назначение:
//   Верхнеуровневый модуль для эксперимента с АЦП на плате MINI_FPGA.
//   - Формирует сигналы управления АЦП (CS, CLK, Address) через модуль AD_Data.
//   - Принимает оцифрованные данные и отображает их на семисегментных индикаторах
//     через модуль Digitron_NumDisplay.
//   - Дополнительно использует PLL для формирования опорной частоты 100 кГц.
// 
// Интерфейс:
//   Входы:
//     CLK           – системный тактовый сигнал FPGA.
//     RSTn          – асинхронный сброс (активный низкий), обычно SW0.
//     AD_EOC        – сигнал "End Of Conversion" от АЦП (завершение преобразования).
//     AD_DigData_In – последовательные цифровые данные от АЦП.
// 
//   Выходы к АЦП:
//     AD_CSn        – сигнал выбора микросхемы АЦП (Chip Select, активный низкий).
//     AD_Clk        – тактовый сигнал для АЦП.
//     AD_Address    – адрес/канал АЦП (обычно выбор входного канала).
//
//   Выходы данных и индикации:
//     Data_Out      – параллельные данные от АЦП (10 бит).
//     CS_Valid_Sig  – флаг валидности данных (строб готовности/валидности выборки).
//     Digitron_Out  – данные для сегментов индикаторов (a–g + точка).
//     DigitronCS_Out– сигналы выбора разрядов индикаторов.
//
// Примечание:
//   Вход AD_EOC в данном верхнем модуле объявлен, но не используется напрямую.
//   Его может обрабатывать нижележащий модуль (например, другая версия AD_Data)
//   либо он оставлен "на будущее" для синхронизации и проверки завершения
//   преобразования.
//
// Автор: (ваше имя / ник)
//=============================================================

module AD
(
    CLK, RSTn, AD_EOC, AD_DigData_In, AD_CSn, AD_Clk, AD_Address, 
    Data_Out, CS_Valid_Sig, Digitron_Out, DigitronCS_Out
);

    //------ Порты верхнего уровня --------------------------------
    input  CLK;          // Системный тактовый сигнал
    input  RSTn;         // Асинхронный сброс (активный низкий), SW0
    
    input  AD_EOC;       // Сигнал завершения преобразования от АЦП (пока не используется)
    input  AD_DigData_In;// Последовательные выходные данные АЦП
    
    output AD_CSn;       // Выбор микросхемы АЦП (Chip Select)
    output AD_Clk;       // Тактовый сигнал АЦП
    output AD_Address;   // Адрес/выбор канала АЦП
    
    output [9:0]Data_Out;        // Параллельные оцифрованные данные от АЦП
    output CS_Valid_Sig;         // Флаг валидности данных
    output [7:0]Digitron_Out;    // Линии сегментов семисегментного индикатора
    output [5:0]DigitronCS_Out;  // Линии выбора разрядов индикаторов

    //=============================================================
    // Модуль U1: AD_Data
    //  - Управляет АЦП (формирует AD_CSn, AD_Clk, AD_Address).
    //  - Принимает последовательные данные AD_DigData_In
    //    и формирует параллельный выход Data_Out (10 бит).
    //  - Выдаёт сигнал CS_Valid_Sig при готовности данных.
    //=============================================================
    AD_Data U1
    (
        .CLK          ( CLK           ), // вход: системный такт
        .RSTn         ( RSTn          ), // вход: сброс
        .AD_DigData_In( AD_DigData_In ), // вход: последовательные данные от АЦП
        .AD_CSn       ( AD_CSn        ), // выход: CS АЦП
        .AD_Clk       ( AD_Clk        ), // выход: такт АЦП
        .AD_Address   ( AD_Address    ), // выход: адрес/канал АЦП
        .Data_Out     ( Data_Out      ), // выход [9:0]: данные в U2 и наружу
        .CS_Valid_Sig ( CS_Valid_Sig  )  // выход: флаг валидности данных
    );
    
    //=============================================================
    // Модуль U2: Digitron_NumDisplay
    //  - Принимает 10-битные данные Data_Out.
    //  - Преобразует их в формат отображения на семисегментных
    //    индикаторах и формирует сигналы Digitron_Out и DigitronCS_Out.
    //=============================================================
    Digitron_NumDisplay U2
    (
        .CLK           ( CLK         ), // вход: системный такт
        .Data          ( Data_Out    ), // вход [9:0]: данные от АЦП
        .Digitron_Out  ( Digitron_Out    ), // выход [7:0]: сегменты
        .DigitronCS_Out( DigitronCS_Out  )  // выход [5:0]: выбор разрядов
    );

    /**************************************************************
    *  PLL для генерации частоты 100 кГц
    *  pll_100K U3:
    *    - Формирует Clk_100K из системного CLK.
    *    - Может использоваться для более точной тактовой частоты
    *      при работе с АЦП или логикой обработки данных.
    **************************************************************/
    wire Clk_100K;

    pll_100K U3 
    (
        .inclk0 ( CLK      ), // вход: системный тактовый сигнал
        .c0     ( Clk_100K )  // выход: несущий такт 100 кГц
    );
    
    /**************************************************************
    *  Альтернативная PLL (закомментирована):
    *
    *  wire Clk_10M;
    *  
    *  PLL2 PLL2_inst
    *  (
    *      .inclk0 ( CLK    ),
    *      .c0     ( Clk_10M )
    *  );
    *
    *  Можно раскомментировать при необходимости формирования
    *  отдельной частоты 10 МГц для экспериментов.
    **************************************************************/

endmodule
