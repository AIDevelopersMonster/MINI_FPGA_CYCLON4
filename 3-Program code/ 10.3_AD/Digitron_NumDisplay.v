//=============================================================
// Модуль: Digitron_NumDisplay
// Назначение:
//   Мультиплексированное отображение 10-битного числа (Data)
//   на шестиразрядном семисегментном индикаторе в HEX-формате.
//   Младшие 10 бит отображаются как шестизначное 24-битное число
//   (Hex_SixNum = {14'b0, Data[9:0]}), то есть фактически это
//   значение от 0 до 1023, выровненное вправо.
//
// Интерфейс:
//   Входы:
//     CLK            – системный тактовый сигнал.
//     Data[9:0]      – 10-битные данные для отображения.
//   Выходы:
//     Digitron_Out[7:0]   – линии сегментов индикатора (a..g + dp).
//     DigitronCS_Out[5:0] – линии выбора разрядов (6 индикаторов).
//
// Принцип работы:
//   - Hex_SixNum разбивается на 6 четырёхбитных тетрад (HEX-цифр).
//   - Регистром W_DigitronCS_Out по кольцу активируется каждый
//     из 6 разрядов по очереди (мультиплексирование).
//   - В зависимости от активного разряда выбирается соответствующая
//     тетрада из Hex_SixNum и декодируется в шаблон сегментов.
//   - На выход Digitron_Out выдаётся инвертированный шаблон
//     (предполагается индикатор с общим анодом или соответствующая
//     логика включения).
//
// Автор: (ваше имя / ник)
//=============================================================

module Digitron_NumDisplay
(
    CLK, Data, Digitron_Out, DigitronCS_Out
);

    input        CLK;
    input  [9:0] Data;
    
    output [7:0] Digitron_Out; 
    output [5:0] DigitronCS_Out;

    // 24-битное HEX-число, в котором задействованы только младшие 10 бит
    wire [23:0] Hex_SixNum;    
    assign Hex_SixNum = {14'b0, Data[9:0]}; // [23:10] = 0, [9:0] = Data

    // "Период" обновления/переключения индикаторов
    // (конкретное время зависит от частоты CLK)
    parameter T100MS = 16'd200;

    reg [7:0] Count;              // Счётчик для смены активного разряда
    reg [3:0] SingleNum;          // Одно 4-битное число (HEX-цифра для текущего разряда)
    reg [7:0] W_Digitron_Out;     // Временная шина сегментов
    reg [7:0] W_DigitronCS_Out;   // Временная шина выбора разрядов

    // Таблица символов для семисегментного индикатора
    // Биты: {dp, g, f, e, d, c, b, a} (зависит от конкретной разводки платы)
    parameter _0 = 8'b1100_0000,
              _1 = 8'b1111_1001,
              _2 = 8'b1010_0100,
              _3 = 8'b1011_0000,
              _4 = 8'b1001_1001,
              _5 = 8'b1001_0010,
              _6 = 8'b1000_0010,
              _7 = 8'b1111_1000,
              _8 = 8'b1000_0000,
              _9 = 8'b1001_0000,
              _A = 8'b1000_1000,
              _B = 8'b1000_0011,
              _C = 8'b1100_0110,
              _D = 8'b1010_0001,
              _E = 8'b1000_0110,
              _F = 8'b1000_1110;

    //=========================================================
    // Мультиплексирование индикаторов
    //   - По достижении Count == T100MS:
    //       * сбрасываем Count;
    //       * циклически сдвигаем W_DigitronCS_Out;
    //       * выбираем соответствующую тетраду из Hex_SixNum;
    //       * по таблице символов формируем W_Digitron_Out.
    //=========================================================
    always @ (posedge CLK)
        begin
            if (Count == T100MS) begin
                // Сброс счётчика периода обновления
                Count <= 8'd0;   

                // Циклический сдвиг маски выбора индикатора:
                // {старший..младший} -> {младший, старший..средние}
                W_DigitronCS_Out = { W_DigitronCS_Out[0],
                                     W_DigitronCS_Out[5:1] };

                // Если ещё не инициализировано, первый раз задаём стартовую маску
                if (W_DigitronCS_Out == 6'd0)
                    W_DigitronCS_Out = 6'b11_1110;  // активен младший разряд

                // Выбор, какое 4-битное число сейчас отображать
                case (W_DigitronCS_Out)
                    6'b11_1110: SingleNum = Hex_SixNum[3:0];    // 0-й разряд (младшая тетрада)
                    6'b11_1101: SingleNum = Hex_SixNum[7:4];    // 1-й разряд
                    6'b11_1011: SingleNum = Hex_SixNum[11:8];   // 2-й разряд
                    6'b11_0111: SingleNum = Hex_SixNum[15:12];  // 3-й разряд
                    6'b10_1111: SingleNum = Hex_SixNum[19:16];  // 4-й разряд
                    6'b01_1111: SingleNum = Hex_SixNum[23:20];  // 5-й разряд (старшая тетрада)
                    default:    SingleNum = 4'd0;
                endcase

                // Декодирование тетрады в шаблон сегментов
                case (SingleNum)
                    4'd0:  W_Digitron_Out = _0;
                    4'd1:  W_Digitron_Out = _1;
                    4'd2:  W_Digitron_Out = _2;
                    4'd3:  W_Digitron_Out = _3;
                    4'd4:  W_Digitron_Out = _4;
                    4'd5:  W_Digitron_Out = _5;
                    4'd6:  W_Digitron_Out = _6;
                    4'd7:  W_Digitron_Out = _7;
                    4'd8:  W_Digitron_Out = _8;
                    4'd9:  W_Digitron_Out = _9;
                    4'd10: W_Digitron_Out = _A;
                    4'd11: W_Digitron_Out = _B;
                    4'd12: W_Digitron_Out = _C;
                    4'd13: W_Digitron_Out = _D;
                    4'd14: W_Digitron_Out = _E;
                    4'd15: W_Digitron_Out = _F;
                    default: W_Digitron_Out = _0;
                endcase
            end
            else begin
                // Пока период не набран – просто инкремент счётчика
                Count <= Count + 1'b1;
            end
        end

    //=========================================================
    // Выходы:
    //   Digitron_Out    – инвертируем шаблон (для нужной полярности).
    //   DigitronCS_Out  – прямое значение маски выбора разрядов.
    //=========================================================
    assign Digitron_Out    = ~W_Digitron_Out;
    assign DigitronCS_Out  = W_DigitronCS_Out;

endmodule
