//   Project: MINI_FPGA Cyclone IV — DA Output Module
//   File: DA.v
//   Author: ChatGPT (formatted for your project style)
//   Function:
//       Генерация 8-битного цифрового сигнала (пилообразная
//       волна) для подачи на параллельный ЦАП (например AD9708).
//
//   Description:
//       - Используется внутренний тактовый сигнал FPGA.
//       - DA_CLK повторяет входной CLK (ЦАП тактируется напрямую).
//       - DA_Data — счётчик от 0 до 255 (sawtooth).
//       - Подходит для AD9708, AD7303, LTC1661 и других параллельных DAC.
//
//   Last update: 2025
//======================================================

module DA
(
    CLK,        // входной тактовый сигнал FPGA
    RSTn,       // асинхронный сброс, активный 0
    DA_CLK,     // тактовый сигнал ЦАП (копия CLK)
    DA_Data     // 8-битные данные на вход ЦАП
);

   input CLK;
   input RSTn;	
   output DA_CLK; 
   output reg [7:0]DA_Data; 

   // 8-битный счётчик для генерации пилообразной волны
   reg [7:0]Count;  

   // ЦАП получает такт напрямую от FPGA
   assign DA_CLK = CLK;		

   //------------------------------------------------------
   //  Основная логика формирования данных для ЦАП
   //
   //  При каждом фронте CLK:
   //     • Count увеличивается на 1
   //     • При достижении 255 — обнуляется
   //     • DA_Data всегда повторяет текущий Count
   //
   //  Таким образом формируется 8-битная цифровая "пила".
   //------------------------------------------------------
   always @(posedge CLK or negedge RSTn)
        if (!RSTn)
            Count <= 0;                       // Сброс
        else if (Count == 8'd255)
        begin
            Count   <= 0;                     // Обнуление счётчика
            DA_Data <= Count[7:0];            // Выходное значение
        end
        else
        begin
            Count   <= Count + 1'b1;          // Инкремент
            DA_Data <= Count[7:0];            // Передача данных в ЦАП
        end

endmodule
