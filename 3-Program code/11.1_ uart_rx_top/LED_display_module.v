//=============================================================
//  Module     : LED_display_module
//  Function   : Отображение принятого UART-байта на LED
//  Author     : (укажи своё имя)
//-------------------------------------------------------------
//  Назначение:
//    Модуль получает сигнал RX_Done_Sig от rx_control_module.
//    Когда приём завершён, он фиксирует байт RX_Data и выводит
//    его на светодиоды LED_Out[7:0].
//
//    Логика проста:
//      • При сбросе — все LED = 0
//      • При импульсе RX_Done_Sig — обновить значение
//      • В остальное время — удерживать предыдущее значение
//
//  Порты:
//    CLK          – системный такт (50 МГц)
//    RSTn         – активный низким уровнем сброс
//    RX_Done_Sig  – флаг завершения приёма UART
//    RX_Data[7:0] – принятый байт данных
//    LED_Out[7:0] – отображаемое значение
//=============================================================

module LED_display_module
(
    CLK,
    RSTn,
    RX_Done_Sig,
    RX_Data,
    LED_Out
);

    input        CLK;
    input        RSTn;
    input        RX_Done_Sig;
    input  [7:0] RX_Data;

    output [7:0] LED_Out;

    //---------------------------------------------------------
    //  Регистр отображаемого значения
    //---------------------------------------------------------
    reg [7:0] rLED_Out;

    always @(posedge CLK or negedge RSTn)
        if(!RSTn)
            rLED_Out <= 8'd0;        // сброс LEDs
        else if(RX_Done_Sig)
            rLED_Out <= RX_Data;     // обновление принятого байта
        else
            rLED_Out <= rLED_Out;    // удержание (можно не писать, но не мешает)

    assign LED_Out = rLED_Out;

endmodule
