//=============================================================
//  Module     : rx_bps_module
//  Function   : Генератор тактов выборки UART (Baud Rate Clock)
//  Author     : (укажи своё имя)
//-------------------------------------------------------------
//  Назначение:
//    Для корректного приёма UART необходимо считывать каждый бит
//    точно в его середине. Данный модуль создаёт короткий импульс
//    BPS_CLK в середине каждого битового интервала.
//
//  Параметры:
//    Частота FPGA : 50 МГц
//    Скорость UART: 9600 бод
//
//    Период UART бита = 50_000_000 / 9600 = 5208 тактов
//    Половина периода (середина бита) = 5208 / 2 = 2604
//
//  Порты:
//    CLK        – системный такт 50 МГц
//    RSTn       – асинхронный сброс (active low)
//    Count_Sig  – разрешение работы генератора bps
//                  (от rx_control_module)
//    BPS_CLK    – короткий импульс, приходящий в середине бита UART
//
//-------------------------------------------------------------
//  Принцип работы:
//    • При Count_Sig = 1 начинается отсчёт Count_BPS.
//    • Счётчик считает от 0 до 5207 (параметр BPS_T - 1).
//    • Когда счётчик достигает половины периода (2604),
//      выдаётся импульс BPS_CLK = 1.
//    • По достижении 5207 счётчик сбрасывается.
//    • Если Count_Sig = 0 — счёт сбрасывается и модуль ждёт запуска.
//=============================================================

module rx_bps_module
(
    CLK,
    RSTn,
    Count_Sig,
    BPS_CLK
);

    input CLK;
    input RSTn;
    input Count_Sig;
    output BPS_CLK;

    //---------------------------------------------------------
    //  Счётчик тактов между выборками UART
    //---------------------------------------------------------
    reg [12:0] Count_BPS;

    // 50_000_000 / 9600 = 5208
    parameter BPS_T = 13'd5208;

    always @(posedge CLK or negedge RSTn)
        if(!RSTn)
            Count_BPS <= 13'd0;
        else if(Count_BPS == BPS_T - 1)
            Count_BPS <= 13'd0;
        else if(Count_Sig)                // Разрешение счёта
            Count_BPS <= Count_BPS + 1'b1;
        else
            Count_BPS <= 13'd0;

    //---------------------------------------------------------
    //  Импульс в середине битового интервала (2604 тактов)
    //  Это оптимальный момент считывания уровня линии RX.
    //---------------------------------------------------------
    assign BPS_CLK = (Count_BPS == 13'd2604) ? 1'b1 : 1'b0;

endmodule


