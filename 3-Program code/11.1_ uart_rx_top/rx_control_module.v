//=============================================================
//  Module     : rx_control_module
//  Function   : Контроллер приёма UART (FSM-приёмник)
//  Author     : (укажи своё имя)
//-------------------------------------------------------------
//  Назначение:
//    Управляет процессом приёма байта по UART:
//      • ждёт старт-бит (переход RX 1→0, сигнал neg_sig);
//      • запускает генератор BPS (Count_Sig);
//      • на импульсах BPS_CLK по центру битового интервала
//        считывает RX_Pin_In и заполняет rData[7:0];
//      • проверяет стоп-бит, подаёт импульс RX_Done_Sig;
//      • передаёт принятый байт в RX_Data.
//
//  Порты:
//    CLK         – системный такт 50 МГц
//    RSTn        – асинхронный сброс (active low)
//    neg_sig     – импульс обнаружения старт-бита (от detect_module)
//    RX_En_Sig   – разрешение приёма (SW1)
//    RX_Pin_In   – линия UART RX
//    BPS_CLK     – такт выборки бита (от rx_bps_module)
//    Count_Sig   – разрешение счёта в rx_bps_module
//    RX_Data[7:0]– принятый байт
//    RX_Done_Sig – флаг окончания приёма (один цикл/несколько циклов)
//
//-------------------------------------------------------------
//  Краткое описание автомата состояний (State):
//    0  – ожидание старт-бита (neg_sig)
//    1  – ожидание середины старт-бита (BPS_CLK)
//    2–9 – приём 8 бит данных (D0..D7) по одному на каждый BPS_CLK
//    10 – ожидание стоп-бита
//    11 – дополнительная задержка/стабилизация
//    12 – выставление флага isDone, остановка счёта BPS
//    13 – сброс флага isDone, возврат в состояние 0
//=============================================================

module rx_control_module
(
    CLK,
    RSTn,

    neg_sig,
    RX_En_Sig,
    RX_Pin_In,
    BPS_CLK,

    Count_Sig,
    RX_Data,
    RX_Done_Sig
);

    //---------- Порты ----------
    input  CLK;
    input  RSTn;

    input  neg_sig;       // импульс обнаружения перехода RX 1→0
    input  RX_En_Sig;     // разрешение приёма
    input  RX_Pin_In;     // данные с линии UART RX
    input  BPS_CLK;       // такт выборки (baud clock)

    output       Count_Sig;     // разрешение счёта в rx_bps_module
    output [7:0] RX_Data;       // принятый байт
    output       RX_Done_Sig;   // флаг завершения приёма

    /********************************************************/

    reg [3:0] State;   // регистр состояния автомата
    reg [7:0] rData;   // регистр для принятого байта ("r" – register)
    reg       isCount; // флаг запуска/остановки счётчика BPS
    reg       isDone;  // флаг завершения приёма

    //---------------------------------------------------------
    //  Основной конечный автомат приёма UART
    //---------------------------------------------------------
    always @(posedge CLK or negedge RSTn)
        if(!RSTn)
        begin
            State   <= 4'd0;
            rData   <= 8'd0;
            isCount <= 1'b0;
            isDone  <= 1'b0;
        end
        else if(RX_En_Sig)               // пока RX_En_Sig = 1, приём разрешён
            case(State)

                // 0: ожидание старт-бита (переход RX 1→0 → neg_sig = 1)
                4'd0:
                    if(neg_sig)
                    begin
                        State   <= State + 1'b1; // → 1
                        isCount <= 1'b1;         // запускаем счётчик BPS
                    end

                // 1: ожидание середины старт-бита
                4'd1:
                    if(BPS_CLK)
                        State <= State + 1'b1;   // → 2

                // 2–9: приём 8 бит данных (D0..D7)
                //      На каждый BPS_CLK считываем очередной бит RX_Pin_In
                4'd2, 4'd3, 4'd4, 4'd5, 4'd6, 4'd7, 4'd8, 4'd9:
                    if(BPS_CLK)
                    begin
                        State <= State + 1'b1;   // двигаемся по битам
                        rData[State - 2] <= RX_Pin_In; // rData[0..7]
                    end

                // 10: ожидание (или выборка) стоп-бита
                4'd10:
                    if(BPS_CLK)
                        State <= State + 1'b1;   // → 11

                // 11: дополнительная задержка/стабилизация
                4'd11:
                    if(BPS_CLK)
                        State <= State + 1'b1;   // → 12

                // 12: завершение приёма, выставление флага isDone
                4'd12:
                begin
                    State   <= State + 1'b1; // → 13
                    isDone  <= 1'b1;
                    isCount <= 1'b0;         // останавливаем счётчик BPS
                end

                // 13: сброс флага isDone и возврат к ожиданию
                4'd13:
                begin
                    State  <= 4'd0; // обратно в ожидание старт-бита
                    isDone <= 1'b0;
                end

            endcase

    /********************************************************/
    //  Выходные сигналы
    /********************************************************/
    assign Count_Sig    = isCount; // управление генератором BPS
    assign RX_Data      = rData;   // принятый байт
    assign RX_Done_Sig  = isDone;  // флаг завершения приёма

endmodule
