//=============================================================
//  Project    : MINI_FPGA Cyclone IV – UART RX
//  File       : rx_top.v
//  Author     : (укажи своё имя)
//  Description: Верхнеуровневый модуль приёма UART-данных.
//               Принимает байт по RX, после успешного приёма
//               отображает его на светодиодах LED7–LED0.
//
//  Порты:
//     CLK        – тактовый сигнал платы (50 МГц).
//     RSTn       – асинхронный сброс, активный низким уровнем (SW0).
//     RX_Pin_In  – входной пин UART-приёмника (F13).
//     RX_En_Sig  – разрешение приёма (SW1).
//     LED_Out[7:0] – индикация принятого байта на светодиодах.
//
//  Внутренние модули:
//     detect_module      – детектор старт-бита (отрицательного фронта).
//     rx_bps_module      – генератор тактов для выбранной скорости UART.
//     rx_control_module  – основная логика приёма байта по UART.
//     LED_display_module – управление отображением принятого байта на LED.
//
//=============================================================

module rx_top
(
    CLK, RSTn, RX_Pin_In, RX_En_Sig, LED_Out
);

    //---------- Порты верхнего уровня ----------
    input  CLK;
    input  RSTn;          // SW0 – общий сброс (active low)
    input  RX_Pin_In;     // F13 – RX-линия UART
    input  RX_En_Sig;     // SW1 – разрешение приёма

    output [7:0] LED_Out; // Выход на светодиоды LED7–LED0

    //---------- Внутренние сигналы ----------
    wire       neg_sig;       // Импульс при обнаружении старт-бита (спада на RX)
    wire       BPS_CLK;       // Такты выборки битов (скорость UART)
    wire       Count_Sig;     // Разрешение отсчёта тактов в генераторе BPS
    wire       RX_Done_Sig;   // Флаг окончания приёма байта
    wire [7:0] RX_Data;       // Принятый байт данных

    /********************************************
     *  U1 – Детектор старт-бита UART
     *  Отслеживает переход RX_Pin_In с 1 на 0
     *  и формирует короткий отрицательный импульс neg_sig,
     *  которым запускается процесс приёма.
     ********************************************/
    detect_module U1
    (
        .CLK      ( CLK      ),
        .RSTn     ( RSTn     ),
        .RX_Pin_In( RX_Pin_In ), // input — от внешнего RX
        .neg_sig  ( neg_sig   )  // output — в U3
    );

    /********************************************
     *  U2 – Генератор тактовой частоты для UART
     *  По сигналу Count_Sig считает системные такты
     *  и формирует импульсы BPS_CLK в моменты выборки
     *  битов приёмника (baud rate).
     ********************************************/
    rx_bps_module U2
    (
        .CLK      ( CLK       ),
        .RSTn     ( RSTn      ),
        .Count_Sig( Count_Sig ), // input — от U3
        .BPS_CLK  ( BPS_CLK   )  // output — в U3
    );

    /********************************************
     *  U3 – Контроллер приёма UART
     *  - Ждёт старт-бит (neg_sig)
     *  - Запускает счётчик bps (Count_Sig)
     *  - На фронтах BPS_CLK считывает битовые значения
     *    с RX_Pin_In
     *  - Формирует байт RX_Data
     *  - По завершении приёма выдаёт RX_Done_Sig
     ********************************************/
    rx_control_module U3
    (
        .CLK        ( CLK        ),
        .RSTn       ( RSTn       ),

        .neg_sig    ( neg_sig    ), // input — от U1
        .RX_En_Sig  ( RX_En_Sig  ), // input — от верхнего уровня (SW1)
        .RX_Pin_In  ( RX_Pin_In  ), // input — сырые данные UART
        .BPS_CLK    ( BPS_CLK    ), // input — такты выборки (от U2)

        .Count_Sig  ( Count_Sig  ), // output — разрешение счёта в U2
        .RX_Data    ( RX_Data    ), // output — принятый байт в U4
        .RX_Done_Sig( RX_Done_Sig ) // output — флаг готовности байта
    );

    /********************************************
     *  U4 – Отображение принятого байта на светодиодах
     *  При приходе импульса RX_Done_Sig фиксирует RX_Data
     *  и выводит его на LED_Out[7:0].
     ********************************************/
    LED_display_module U4
    (
        .CLK        ( CLK        ),
        .RSTn       ( RSTn       ),
        .RX_Done_Sig( RX_Done_Sig ), // input — от U3
        .RX_Data    ( RX_Data    ),   // input — от U3
        .LED_Out    ( LED_Out    )    // output — на верхний уровень
    );

endmodule
