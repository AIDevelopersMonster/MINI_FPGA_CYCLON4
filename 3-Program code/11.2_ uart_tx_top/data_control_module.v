//======================================================
//  Project   : MINI_FPGA Cyclone IV — UART TX
//  Module    : data_control_module
//  Function  : Управление данными для передатчика UART.
//              Периодически (раз в 0.5 секунды при 50 МГц)
//              формирует байт TX_Data и включает сигнал
//              TX_En_Sig, разрешающий передачу.
//              Последовательно отправляются значения:
//              0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F.
//======================================================

module data_control_module
(
    CLK,        // Тактовый сигнал FPGA
    RSTn,       // Асинхронный сброс, активный нулём
    TX_Done_Sig,// Флаг "кадр UART отправлен" от tx_control_module
    TX_En_Sig,  // Разрешение передачи (состояние "идёт передача")
    TX_Data     // Выходные параллельные данные на отправку
);

    input  wire       CLK;
    input  wire       RSTn;

    input  wire       TX_Done_Sig;
    output wire       TX_En_Sig;
    output wire [7:0] TX_Data;

    reg        isTX;        // 1 — передача разрешена/идёт, 0 — ожидание
    reg [7:0]  rTX_Data;    // Регистр с текущим байтом данных
    reg [3:0]  i;           // Счётчик номера отправляемого байта (0..5)
    reg [31:0] Count;       // Счётчик для формирования интервала 0.5 секунды

    // Период 0.5 секунды при тактовой частоте 50 МГц:
    // 0.5 c * 50_000_000 Гц = 25_000_000 тактов
    parameter T05S = 32'd25_000_000;

    // Набор данных, которые по кругу отправляются в UART
    parameter _0A = 8'b0000_1010,
              _0B = 8'b0000_1011,
              _0C = 8'b0000_1100,
              _0D = 8'b0000_1101,
              _0E = 8'b0000_1110,
              _0F = 8'b0000_1111;

    // --------------------------------------------------
    // Основной процесс:
    //  - управляет флагом isTX;
    //  - формирует задержку между отправками (Count);
    //  - выбирает следующий байт rTX_Data по счётчику i.
    // --------------------------------------------------
    always @ ( posedge CLK or negedge RSTn )
    begin
        if( !RSTn )
            begin
                isTX   <= 1'b0;          // Передача запрещена
                i      <= 4'd5;          // Начинаем с последнего байта (_0F)
                Count  <= 32'd0;         // Обнуляем счётчик времени
                rTX_Data <= _0F;         // Можно инициализировать стартовым значением
            end
        else if( TX_Done_Sig == 1'b1 )
            begin
                // Кадр отправлен — снимаем флаг "идёт передача"
                isTX  <= 1'b0;
                Count <= Count + 1'b1;   // Начинаем/продолжаем отсчёт паузы
            end
        else if ( Count == T05S - 1 )
            begin
                // Прошла пауза 0.5 c — запускаем следующую передачу
                isTX  <= 1'b1;           // Разрешаем передачу UART
                Count <= 32'd0;          // Сбрасываем счётчик интервала

                // Переход к следующему байту в последовательности
                if( i == 4'd5 )
                    i <= 4'd0;
                else
                    i <= i + 1'b1;
            end
        else
            begin
                // Просто считаем такты до истечения интервала 0.5 c
                Count <= Count + 1'b1;
            end

        // Выбор значения rTX_Data по индексу i
        case( i )
            4'd0: rTX_Data <= _0A;
            4'd1: rTX_Data <= _0B;
            4'd2: rTX_Data <= _0C;
            4'd3: rTX_Data <= _0D;
            4'd4: rTX_Data <= _0E;
            4'd5: rTX_Data <= _0F;
            default: rTX_Data <= _0A;    // Защита от "левых" значений i
        endcase
    end

    // Привязка внутренних регистров к выходам
    assign TX_Data   = rTX_Data;
    assign TX_En_Sig = isTX;

endmodule
