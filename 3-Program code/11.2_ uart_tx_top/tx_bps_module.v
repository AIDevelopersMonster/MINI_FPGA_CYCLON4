//======================================================
//  Project   : MINI_FPGA Cyclone IV — UART TX
//  Module    : tx_bps_module
//  Function  : Генератор бод-частоты для UART.
//              Формирует одиночный импульс BPS_CLK
//              ровно в середине каждого битового интервала.
//              
//              При частоте FPGA = 50 MHz и скорости UART = 9600 бод:
//                 BPS_T = 50_000_000 / 9_600 ≈ 5208 тактов
//              Середина периода:
//                 5208 / 2 = 2604
//======================================================

module tx_bps_module
(
    CLK,        // Системный такт 50 MHz
    RSTn,       // Асинхронный сброс (активный низким)
    Count_Sig,  // Разрешение работы счётчика бод (1 = считать)
    BPS_CLK     // Импульс середины битового такта UART
);

    input  wire CLK;
    input  wire RSTn;
    input  wire Count_Sig;
    output wire BPS_CLK;

    // --------------------------------------------------
    // Счётчик тактов для формирования периода битового такта.
    // --------------------------------------------------
    reg [12:0] Count_BPS;

    // 50 MHz / 9600 бод = 5208 тактов на один бит
    parameter BPS_T = 13'd5208;

    // --------------------------------------------------
    // Логика формирования счётчика:
    //   - сброс при RSTn = 0;
    //   - счёт идёт только пока Count_Sig = 1 (идёт передача);
    //   - при достижении конца периода — сброс счётчика в ноль.
    // --------------------------------------------------
    always @ (posedge CLK or negedge RSTn)
    begin
        if (!RSTn)
            Count_BPS <= 13'd0;
        else if (Count_BPS == BPS_T - 1)
            Count_BPS <= 13'd0;
        else if (Count_Sig)               // Разрешение счёта бод
            Count_BPS <= Count_BPS + 1'b1;
        else
            Count_BPS <= 13'd0;
    end

    // --------------------------------------------------
    // Формирование BPS_CLK:
    // Импульс появляется ровно в центре битового интервала —
    // когда Count_BPS == 2604.
    // UART "выбирает" бит именно в середине его длительности,
    // обеспечивая устойчивость к джиттеру.
    // --------------------------------------------------
    assign BPS_CLK = (Count_BPS == 13'd2604) ? 1'b1 : 1'b0;

endmodule
