//======================================================
//  Project   : MINI_FPGA Cyclone IV — UART TX
//  Module    : tx_control_module
//  Function  : Управление передачей UART.
//              По сигналу TX_En_Sig и такту BPS_CLK
//              последовательно выдаёт биты TX_Data
//              на линию TX_Pin_Out в формате UART:
//                  - 1 старт-бит (0)
//                  - 8 бит данных (TX_Data[0]..TX_Data[7])
//                  - 1 стоп-бит (1)
//              Дополнительно даёт импульс TX_Done_Sig
//              по завершении посылки кадра.
//======================================================

module tx_control_module
(
    CLK,          // Системный тактовый сигнал
    RSTn,         // Асинхронный сброс, активный низким уровнем
    TX_En_Sig,    // Разрешение передачи кадра (от data_control_module)
    BPS_CLK,      // Такт UART (импульс в середине битового интервала)
    TX_Data,      // Параллельные данные для отправки
    TX_Done_Sig,  // Флаг "кадр передан"
    TX_Pin_Out    // Линия TX (к пину FPGA и дальше к UART-USB / COM-порту)
);

    input  wire       CLK;
    input  wire       RSTn;

    input  wire       TX_En_Sig;
    input  wire       BPS_CLK;
    input  wire [7:0] TX_Data;

    output wire       TX_Done_Sig;
    output wire       TX_Pin_Out;

    /********************************************************/

    reg [3:0] State;   // Текущее состояние автомата передачи (номер бита/этапа)
    reg       rTX;     // Регистр выхода TX (фактический уровень на линии)
    reg       isDone;  // Внутренний флаг окончания передачи

    // ------------------------------------------------------
    // FSM по такту CLK:
    //   - формирование стартового бита
    //   - последовательная передача 8 бит данных
    //   - формирование стоп-бита
    //   - генерация импульса TX_Done_Sig
    //   - возврат в исходное состояние
    // Передвигаемся по состояниям только тогда, когда:
    //   TX_En_Sig = 1 и приходит импульс BPS_CLK.
    // ------------------------------------------------------
    always @ (posedge CLK or negedge RSTn)
    begin
        if (!RSTn)
            begin
                State  <= 4'd0;
                rTX    <= 1'b1;   // Линия TX в неактивном (стоп) состоянии
                isDone <= 1'b0;
            end
        else if (TX_En_Sig)      // Пока TX_En_Sig = 1, передача разрешена
            case (State)

                // ------------------------------------------
                // State 0: старт-бит (0)
                // ------------------------------------------
                4'd0 :
                    if (BPS_CLK)
                        begin
                            State <= State + 1'b1;
                            rTX   <= 1'b0;    // Старт-бит = 0
                        end

                // ------------------------------------------
                // State 1..8: 8 бит данных (LSB first)
                // Передаём TX_Data[0]..TX_Data[7]
                // ------------------------------------------
                4'd1, 4'd2, 4'd3, 4'd4,
                4'd5, 4'd6, 4'd7, 4'd8 :
                    if (BPS_CLK)
                        begin
                            State <= State + 1'b1;
                            // Передача соответствующего бита данных:
                            // при State=1 → TX_Data[0],
                            // при State=2 → TX_Data[1], ...
                            rTX   <= TX_Data[ State - 1 ];
                        end

                // ------------------------------------------
                // State 9: стоп-бит (1)
                // ------------------------------------------
                4'd9 :
                    if (BPS_CLK)
                        begin
                            State <= State + 1'b1;
                            rTX   <= 1'b1;    // Стоп-бит = 1
                        end

                // ------------------------------------------
                // State 10: дополнительный такт "стоп/идл"
                // (линия остаётся в 1, можно считать
                //  вторым стоп-битом или просто паузой)
                // ------------------------------------------
                4'd10 :
                    if (BPS_CLK)
                        begin
                            State <= State + 1'b1;
                            rTX   <= 1'b1;
                        end

                // ------------------------------------------
                // State 11: помечаем окончание передачи
                // ------------------------------------------
                4'd11 :
                    if (BPS_CLK)
                        begin
                            State  <= State + 1'b1;
                            isDone <= 1'b1;   // Устанавливаем флаг "готово"
                        end

                // ------------------------------------------
                // State 12: возврат в исходное состояние
                //  - сбрасываем флаг окончания
                //  - возвращаемся к State 0
                // ------------------------------------------
                4'd12 :
                    begin
                        State  <= 4'd0;
                        isDone <= 1'b0;
                    end

                // (опционально можно добавить default, но
                //  в учебном примере и так всё покрыто)
            endcase
        else
            begin
                // При TX_En_Sig = 0 состояние не меняем,
                // уровень на TX сохраняем (линия "зависает" в последнем значении).
                rTX <= rTX;
            end
    end

    /********************************************************/

    assign TX_Pin_Out  = rTX;     // Физический вывод TX
    assign TX_Done_Sig = isDone;  // Флаг "кадр отправлен"

    /********************************************************/

endmodule
