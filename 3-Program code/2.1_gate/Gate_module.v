//-------------------------------------------------------------
// 2.1 Gate_module — модуль логических элементов
// Проект: MINI_FPGA (Cyclone IV)
//-------------------------------------------------------------
// Назначение:
//   Выполняет базовые логические операции над двумя входными
//   сигналами Gate_In[1:0] и выводит результаты на 6 выходов.
//   Каждый бит Gate_Out соответствует конкретной логической
//   операции.
//
// Порты:
//   Gate_In   — 2-битный вход (два логических сигнала)
//   Gate_Out  — 6-битный выход (результаты всех операций)
//
//   Gate_Out[0] — AND
//   Gate_Out[1] — NAND
//   Gate_Out[2] — OR
//   Gate_Out[3] — NOR
//   Gate_Out[4] — XOR
//   Gate_Out[5] — XNOR
//
// Автор: MINI_FPGA_CYCLON4
//-------------------------------------------------------------

module Gate_module
(
    Gate_In, 
    Gate_Out
);

    input  [1:0] Gate_In;        // Вход: два логических сигнала
    output reg [5:0] Gate_Out;   // Выход: шесть логических операций
 
    // -----------------------------------------------------------------
    // Комбинаторный блок: вычисление логических операций при изменении
    // любого входного сигнала. Используем Gate_In[0] и Gate_In[1].
    // -----------------------------------------------------------------
    always @ (Gate_In[0] or Gate_In[1]) 
    begin 
        Gate_Out[0] = Gate_In[0] &  Gate_In[1];   // AND
        Gate_Out[1] = ~(Gate_In[0] &  Gate_In[1]); // NAND
        Gate_Out[2] = Gate_In[0] |  Gate_In[1];   // OR
        Gate_Out[3] = ~(Gate_In[0] |  Gate_In[1]); // NOR
        Gate_Out[4] = Gate_In[0] ^  Gate_In[1];   // XOR
        Gate_Out[5] = Gate_In[0] ~^ Gate_In[1];   // XNOR
    end
		 
endmodule
