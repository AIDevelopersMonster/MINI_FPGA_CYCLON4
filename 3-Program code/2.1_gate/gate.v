//-------------------------------------------------------------
// 2.1 Gate — верхний модуль для демонстрации работы логических
//          элементов на FPGA Cyclone IV (проект MINI_FPGA)
//-------------------------------------------------------------
// Назначение:
//   Модуль gate служит "обёрткой" (top-level), принимая входы с
//   переключателей SW_In и передавая их во внутренний модуль
//   Gate_module, который вычисляет результаты логических операций.
//
// Порты:
//   SW_In   — входные сигналы с переключателей (2 бита)
//   LED_Out — выход на светодиоды (6 бит, результат логических операций)
//
// Автор: MINI_FPGA_CYCLON4
//-------------------------------------------------------------

module gate
(
    SW_In,      // Двухбитный вход с переключателей
    LED_Out     // Шестибитный выход на светодиоды
);

    input  [1:0] SW_In;     // Вход: SW0–SW1
    output [5:0] LED_Out;   // Выход: LED0–LED5

    // ---------------------------------------------------------
    // Экземпляр модуля Gate_module
    // Передаём ему входы и принимаем назад вычисленные значения
    // ---------------------------------------------------------

    Gate_module U1
    (
        .Gate_In ( SW_In  ),   // input  [1:0] — передаём входные сигналы
        .Gate_Out( LED_Out )   // output [5:0] — принимаем результаты логических операций
    );

endmodule
