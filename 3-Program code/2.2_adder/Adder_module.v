//=============================================================
//  MINI_FPGA (Cyclone IV) — Базовые цифровые модули
//  Модуль: Adder_module (полный однобитный сумматор)
//-------------------------------------------------------------
//  Назначение:
//      Реализует полный однобитный сумматор (Full Adder):
//      принимает два разрядных входа A и B и входной перенос Cin,
//      формирует сумму S и выходной перенос Cout.
//-------------------------------------------------------------
//  Логические выражения:
//
//      S     = A ⊕ B ⊕ Cin
//      Cout  = (A & B) | (Cin & (A ⊕ B))
//
//  Это соответствует классической схеме полного сумматора.
//-------------------------------------------------------------
//  Порты:
//      a      — первый операнд (A)
//      b      — второй операнд (B)
//      c_in   — входной перенос (Cin)
//      s      — сумма (S)
//      c_out  — выходной перенос (Cout)
//=============================================================

module Adder_module
(
    a,
    b,
    c_in,
    s,
    c_out
);

    input  wire a;       // операнд A
    input  wire b;       // операнд B
    input  wire c_in;    // входной перенос Cin

    output wire s;       // сумма S
    output wire c_out;   // выходной перенос Cout (Carry)

    //---------------------------------------------------------
    //  Логика полного сумматора
    //---------------------------------------------------------
    assign s     = c_in ^ a ^ b;
    assign c_out = (a & b) | (c_in & (a ^ b));

endmodule
