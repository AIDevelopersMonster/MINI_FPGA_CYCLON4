//=============================================================
//  MINI_FPGA (Cyclone IV) — Базовые цифровые модули
//  Модуль: adder (верхний уровень)
//-------------------------------------------------------------
//  Назначение:
//  Передаёт входные сигналы от переключателей SW на модуль
//  полного однобитного сумматора (Adder_module), а его выводы
//  направляет на светодиоды LED.
//-------------------------------------------------------------
//  Порты:
//      SW_In[2] — входной перенос (Cin)
//      SW_In[1] — первый операнд (A)
//      SW_In[0] — второй операнд (B)
//
//      LED_Out[0] — сумма (S)
//      LED_Out[1] — выходной перенос (Cout)
//=============================================================

module adder
(
    SW_In,
    LED_Out
);

    input  [2:0] SW_In;     // {Cin, A, B}
    output [1:0] LED_Out;   // {Cout, S}

    //---------------------------------------------------------
    //  Экземпляр модуля полного однобитного сумматора
    //---------------------------------------------------------
    Adder_module U1
    (
        .a     ( SW_In[1]  ),   // операнд A
        .b     ( SW_In[0]  ),   // операнд B
        .c_in  ( SW_In[2]  ),   // входной перенос Cin

        .s     ( LED_Out[0] ),  // сумма S
        .c_out ( LED_Out[1] )   // выходной перенос Cout
    );

endmodule
