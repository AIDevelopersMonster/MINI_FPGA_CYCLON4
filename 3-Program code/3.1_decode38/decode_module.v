// File: decode_module.v
// Description: 3-to-8 line decoder. 
//               Converts 3 input bits (a2,a1,a0) into 8 outputs y7..y0.
// Author: AIDevelopersMonster
// ============================================================

module decode_module
(
    a2, a1, a0,       // Вход: 3-битовый двоичный код
    y7, y6, y5, y4,
    y3, y2, y1, y0    // Выход: одноактивная линия из 8
);

    // ------------------------------
    // Порты
    // ------------------------------
    input  wire a2, a1, a0;
    output wire y7, y6, y5, y4, y3, y2, y1, y0;

    // ------------------------------
    // Логические выражения из таблицы истинности 3→8
    // Активный «1» появляется только на одном выходе,
    // соответствующем входному коду a2a1a0.
    // ------------------------------

    assign y0 = ~a2 & ~a1 & ~a0;   // 000 → 0000_0001
    assign y1 = ~a2 & ~a1 &  a0;   // 001 → 0000_0010
    assign y2 = ~a2 &  a1 & ~a0;   // 010 → 0000_0100
    assign y3 = ~a2 &  a1 &  a0;   // 011 → 0000_1000
    assign y4 =  a2 & ~a1 & ~a0;   // 100 → 0001_0000
    assign y5 =  a2 & ~a1 &  a0;   // 101 → 0010_0000
    assign y6 =  a2 &  a1 & ~a0;   // 110 → 0100_0000
    assign y7 =  a2 &  a1 &  a0;   // 111 → 1000_0000

endmodule

