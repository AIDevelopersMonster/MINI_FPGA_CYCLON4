//=======================================================
// 8-to-3 Priority Encoder (Priority: x[7] → x[0])
// Project: MINI_FPGA_CYCLON4
// File: pencode_module.v
// Description:
//   Приоритетный 8-к-3 кодировщик.
//   Сканирует входной вектор x[7:0] на каждом фронте CLK.
//   Если найден хотя бы один активный вход,
//   устанавливает Valid = 1 и выводит индекс младшего
//   найденного бита (i). При нескольких '1' победит тот,
//   что встречен последним в цикле (x[7] имеет макс. приоритет).
//=======================================================

module pencode_module
(
    CLK, 
    x, 
    y, 
    Valid
);

    input        CLK;
    input  [7:0] x;        // входные линии
    output reg [2:0] y;    // 3-битный результат
    output reg       Valid;// признак наличия хотя бы одного '1'

    integer i;

    //===================================================
    // Priority encoder logic
    //===================================================
    always @(posedge CLK)
    begin
        y     <= 3'b000;   // значение по умолчанию
        Valid <= 1'b0;

        // Сканируем входы от 0 до 7
        // При совпадении — записываем номер бита
        // Последний найденный '1' переопределяет предыдущий
        for (i = 0; i <= 7; i = i + 1)
            if (x[i] == 1'b1)
            begin
                y     <= i[2:0]; // номер активного бита
                Valid <= 1'b1;   // есть хотя бы один '1'
            end
    end

endmodule

	