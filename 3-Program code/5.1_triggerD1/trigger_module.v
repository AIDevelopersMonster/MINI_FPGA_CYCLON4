//=============================================================
//  Project: MINI_FPGA (Cyclone IV)
//  Module:  trigger_module
//  File:    trigger_module.v
//
//  Description:
//      D-триггер на уровне логических вентилей (gate-level).
//      Используются NAND-элементы для реализации:
//
//         • Асинхронный Setn  (установка Q = 1, active low)
//         • Асинхронный Clrn  (сброс Q = 0, active low)
//         • Сэмплирование входа D по фронту CLK
//
//      Реализует классическую SR-Latch + мастер-слейв структуру.
//
//=============================================================

module trigger_module
(
    CLK,     // Тактовый сигнал
    Setn,    // Асинхронная установка (active low)
    Clrn,    // Асинхронный сброс (active low)
    D,       // Вход данных D
    Q        // Основной выход Q
);

    //--------------- Объявление портов ----------------//
    input  wire CLK;
    input  wire Setn;   // При Setn = 0 → Q устанавливается в 1
    input  wire Clrn;   // При Clrn = 0 → Q сбрасывается в 0
    input  wire D;      // Значение, записываемое в триггер
    output wire Q;      // Выход триггера

    //--------------- Внутренние сигналы ---------------//
    wire f1, f2, f3, f4, f5, f6;

    //--------------- Логическая схема триггера --------//
    // Функциональная структура соответствует реальному gate-level
    // D-триггеру, собранному на NAND-элементах.
    //
    // Здесь используется цепочка из двух RS-защёлок
    // (master + slave), переключаемых сигналом CLK.
    //

    nand U1 ( f1, Setn, f4, f2 );       // Формирование Q (slave latch)
    nand U2 ( f2, f1, f5, Clrn );       // Управление обратной связью slave
    nand U3 ( f3, Setn, f6, f4 );       // Мастер-защёлка (формирование S)
    nand U4 ( f4, f3, CLK, Clrn );      // Управление мастер-защёлкой
    nand U5 ( f5, f4, Setn, CLK, f6 );  // Логика передачи уровня
    nand U6 ( f6, f5, D, Clrn );        // Вход D, воздействующий на master

    // Выход триггера
    assign Q = f1;

endmodule
