//==============================================================
// MINI_FPGA (Cyclone IV)
// Module: triggerJK1
// Description: 
//   Топ-модуль для 8-битного JK-триггера, разбитого на две группы:
//     • J[7:4] / K[7:4]  → Q[7:4]
//     • J[3:0] / K[3:0]  → Q_n[3:0]
//   Управление: асинхронные входы Setn и Clrn, синхронизация по CLK.
//
// Author: AIDevelopersMonster
// Project: MINI_FPGA_CYCLON4
//==============================================================

module triggerJK1
(	
    CLK, Setn, Clrn, Sw_In, LED_Out
);

    input  wire        CLK;      // Синхросигнал
    input  wire        Setn;     // Асинхр. установка (active low)
    input  wire        Clrn;     // Асинхр. сброс    (active low)
    input  wire [7:0]  Sw_In;    // Верхние 4 бита → J[7:4], нижние 4 → K[3:0]
    output wire [7:0]  LED_Out;  // Индикация состояний Q и Q_n

    //==========================================================
    // Подключение внутреннего модуля JK-триггера
    //==========================================================
    trigger_module U1
    (
        .CLK ( CLK ),         // Тактирование
        .Setn( Setn ),        // Установка (низкий уровень активен)
        .Clrn( Clrn ),        // Сброс    (низкий уровень активен)

        .J   ( Sw_In[7:4] ),  // J-входы
        .K   ( Sw_In[3:0] ),  // K-входы

        .Q   ( LED_Out[7:4] ), // Прямой выход
        .Q_n ( LED_Out[3:0] )  // Инверсный выход
    );

endmodule
