//==============================================================
// MINI_FPGA (Cyclone IV)
// Module: trigger_module
// Description: 
//   4-разрядный JK-триггер с делителем тактовой частоты.
//   Входы J[3:0], K[3:0], выходы Q[3:0] и инверсные Q_n[3:0].
//   Тактирование идёт от делённого сигнала CLK1.
// 
//   Формула JK-триггера для каждого бита i:
//     Q_next = J[i] & ~Q[i]  |  ~K[i] & Q[i]
//   В схеме используется Q_n[i] вместо ~Q[i].
//
//   Setn, Clrn — активны низким уровнем, логически
//   «подмешиваются» к выходу (установка/сброс).
//
// Author: AIDevelopersMonster
// Project: MINI_FPGA_CYCLON4
//==============================================================

module trigger_module
(	
    CLK, Setn, Clrn, J, K, Q, Q_n
);
    input  wire       CLK;     // Входной тактовый сигнал от платы
    input  wire       Setn;    // Установка (active low)
    input  wire       Clrn;    // Сброс    (active low)
    input  wire [3:0] J;       // Входы J для 4 JK-триггеров
    input  wire [3:0] K;       // Входы K для 4 JK-триггеров
    output reg  [3:0] Q;       // Прямые выходы триггеров
    output reg  [3:0] Q_n;     // Инверсные выходы триггеров

    //==========================================================
    // Делитель частоты: формируем более медленный тактовый CLK1
    // Параметр Timex задаёт период переключения CLK1.
    //==========================================================
    reg        CLK1 = 1'b0;          // Медленный тактовый сигнал
    reg [20:0] Count;                // Счётчик для делителя частоты

    parameter Timex = 21'd2000_000;   // Кол-во тактов CLK до переключения CLK1

    // Делитель частоты
    always @ (posedge CLK)
    begin
        if (Count == Timex - 1'b1) begin
            Count <= 21'd0;          // Сбрасываем счётчик
            CLK1  <= ~CLK1;          // Инвертируем медленный тактовый
        end
        else begin
            Count <= Count + 21'd1;  // Инкремент счётчика
        end
    end

    //==========================================================
    // JK-триггеры на медленном тактовом сигнале CLK1
    // Логика для каждого бита:
    //   Q_next = (J & Q_n) | (~K & Q)
    //   Затем добавлены Setn и Clrn:
    //   Q = (Q_next & Setn & Clrn) | ~Setn
    //
    //   • Setn = 0 → Q = 1 (установка)
    //   • Clrn = 0 и Setn = 1 → Q = 0 (сброс)
    //   • Setn = 1, Clrn = 1 → обычная JK-логика
    //==========================================================
    always @ (posedge CLK1)
    begin
        // Бит 0
        Q[0]   <= ( ( (J[0] & Q_n[0]) | (~K[0] & Q[0]) ) & Setn & Clrn ) | ~Setn;
        // Бит 1
        Q[1]   <= ( ( (J[1] & Q_n[1]) | (~K[1] & Q[1]) ) & Setn & Clrn ) | ~Setn;
        // Бит 2
        Q[2]   <= ( ( (J[2] & Q_n[2]) | (~K[2] & Q[2]) ) & Setn & Clrn ) | ~Setn;
        // Бит 3
        Q[3]   <= ( ( (J[3] & Q_n[3]) | (~K[3] & Q[3]) ) & Setn & Clrn ) | ~Setn;

        // Инверсные выходы — просто отрицание Q
        Q_n[0] <= ~Q[0];
        Q_n[1] <= ~Q[1];
        Q_n[2] <= ~Q[2];
        Q_n[3] <= ~Q[3];
    end

endmodule
