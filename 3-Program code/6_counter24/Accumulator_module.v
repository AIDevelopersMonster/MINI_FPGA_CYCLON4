//  Module Name : Accumulator_module
//  Project     : MINI_FPGA (Cyclone IV)
//  File        : Accumulator_module.v
//  Function    : 24-ричный счётчик (0..23) с делителем частоты.
//                Делитель формирует медленный тактовый сигнал CLK1 из быстрого
//                системного CLK, а на фронтах CLK1 увеличивается двузначный
//                BCD-счётчик Result (десятки/единицы).
//
//  Author      : (your name / nickname)
//  Date        : (yyyy-mm-dd)
// -----------------------------------------------------------------------------
//  Порты:
//      CLK         - системный тактовый сигнал (например, 50 МГц)
//      RSTn        - асинхронный сброс, активный низкий уровень (0)
//      Result[7:0] - выходное значение счётчика в виде двух BCD-цифр:
//                    Result[7:4] — десятки, Result[3:0] — единицы.
//                    Диапазон значений: 00..23.
// -----------------------------------------------------------------------------
//  Принцип работы:
//      1) Первый always-блок — делитель частоты:
//         - считает такты до T05S - 1,
//         - затем сбрасывает Count и инвертирует CLK1;
//         - при CLK = 50 МГц и T05S = 25_000_000 период CLK1 ≈ 1 секунда.
//      2) Второй always-блок — двузначный BCD-счётчик по модулю 24:
//         - при RSTn = 0 счётчик сбрасывается в 00;
//         - при достижении 23 (2 и 3) счётчик возвращается в 00;
//         - при 09 → 10, иначе инкрементируется младшая цифра.
// -----------------------------------------------------------------------------

module Accumulator_module
(
    CLK, RSTn, Result
);

    input        CLK;           // системный тактовый сигнал
    input        RSTn;          // асинхронный сброс (активный 0)
    output reg [7:0] Result;    // двухразрядный счётчик в формате BCD

    // -------------------------------------------------------------------------
    // Делитель частоты для формирования медленного тактового сигнала CLK1
    // -------------------------------------------------------------------------
    reg        CLK1 = 1'b0;     // делённый тактовый сигнал (примерно 1 Гц)
    reg [25:0] Count;           // счётчик для делителя

    // При CLK = 50 МГц и T05S = 25_000_000:
    // - Count считает от 0 до 24_999_999,
    // - затем сбрасывается и инвертирует CLK1,
    // - полный период CLK1 ≈ 1 секунда.
    parameter T05S = 26'd25_000_000;   // половина периода CLK1 в тактах CLK

    // Делитель частоты
    always @ (posedge CLK) begin
        if (Count == T05S - 26'b1) begin
            Count <= 26'd0;
            CLK1  <= ~CLK1;
        end
        else begin
            Count <= Count + 26'd1;
        end
    end

    // -------------------------------------------------------------------------
    // BCD-счётчик 0..23, работающий на медленном тактовом сигнале CLK1
    // -------------------------------------------------------------------------
    always @ (posedge CLK1 or negedge RSTn) begin
        if (!RSTn) begin
            // Асинхронный сброс: значение 00
            Result[7:4] <= 4'd0;   // десятки
            Result[3:0] <= 4'd0;   // единицы
        end
        // Если достигли 23 — следующий шаг снова 00
        else if (Result[7:4] == 4'd2 && Result[3:0] == 4'd3) begin
            Result[7:4] <= 4'd0;
            Result[3:0] <= 4'd0;
        end
        // Если младшая цифра = 9 — переход к следующей десятке
        else if (Result[3:0] == 4'd9) begin
            Result[3:0] <= 4'd0;
            Result[7:4] <= Result[7:4] + 1'b1;
        end
        // Обычное инкрементирование младшей цифры
        else begin
            Result[3:0] <= Result[3:0] + 1'b1;
        end
    end

endmodule
