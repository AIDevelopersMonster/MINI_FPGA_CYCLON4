// -----------------------------------------------------------------------------
//  Module Name : Digitron_NumDisplay_module
//  Project     : MINI_FPGA (Cyclone IV)
//  File        : Digitron_NumDisplay_module.v
//  Function    : Драйвер динамической индикации для 7-сегментных индикаторов.
//                Отображает двухразрядное число, закодированное в шине Result
//                (младший и старший полубайт: Result[3:0], Result[7:4]) на
//                многоразрядном индикаторе через мультиплексирование разрядов.
//
//  Author      : (your name / nickname)
//  Date        : (yyyy-mm-dd)
// -----------------------------------------------------------------------------
//  Порты:
//      CLK             - тактовый сигнал FPGA
//      Result[7:0]     - входное значение для индикации:
//                        Result[3:0] — младшая цифра (единицы),
//                        Result[7:4] — старшая цифра (десятки).
//      Digitron_Out    - шина сегментов индикатора (a..g + dp)
//      DigitronCS_Out  - шина выбора разрядов (chip select для 6 цифр)
// -----------------------------------------------------------------------------
//  Принцип работы:
//      - Счётчик Count делит частоту тактового сигнала, чтобы периодически
//        переключать активный разряд индикатора.
//      - Линии DigitronCS_Out по очереди активируют нужную цифру
//        (в данном варианте используются только две позиции).
//      - Для каждой активной позиции из Result выбирается нужный полубайт
//        (SingleNum), далее он преобразуется в шаблон сегментов W_Digitron_Out.
//      - Быстрое переключение разрядов даёт эффект «статического» горения
//        двух цифр с точки зрения глаза.
// -----------------------------------------------------------------------------

module Digitron_NumDisplay_module
(
    CLK, Result, Digitron_Out, DigitronCS_Out
);

    input        CLK;                // системный тактовый сигнал
    input  [7:0] Result;             // входное число: десятки и единицы (BCD/0..99)

    output [7:0] Digitron_Out;       // выход на сегменты индикатора
    output [5:0] DigitronCS_Out;     // выбор разряда (6 позиций на плате)

    // -------------------------------------------------------------------------
    // Делитель частоты для динамической индикации
    // Timex определяет, как часто будет переключаться активный разряд.
    // При больших значениях Timex — индикация медленнее (вплоть до мерцания),
    // при меньших — быстрее.
    // -------------------------------------------------------------------------
    parameter Timex = 8'd200;

    reg [7:0] Count;                 // счётчик тиков для переключения разрядов

    reg [3:0] SingleNum;             // текущая отображаемая цифра (0..9)
    reg [7:0] W_Digitron_Out;        // шаблон сегментов для текущей цифры
    reg [5:0] W_DigitronCS_Out;      // регистр выбора активного разряда

    // -------------------------------------------------------------------------
    // Кодировка цифр 0–9 для 7-сегментного индикатора
    // Формат: {dp, g, f, e, d, c, b, a} или другой, в зависимости от платы.
    // Здесь предполагается, что '1' — сегмент включен, '0' — выключен.
    // -------------------------------------------------------------------------
    parameter _0 = 8'b0011_1111,
              _1 = 8'b0000_0110,
              _2 = 8'b0101_1011,
              _3 = 8'b0100_1111,
              _4 = 8'b0110_0110,
              _5 = 8'b0110_1101,
              _6 = 8'b0111_1101,
              _7 = 8'b0000_0111,
              _8 = 8'b0111_1111,
              _9 = 8'b0110_1111;

    // -------------------------------------------------------------------------
    // Основной процесс динамической индикации
    // -------------------------------------------------------------------------
    always @ (posedge CLK)
    begin
        if (Count == Timex) begin
            Count <= 8'd0;

            // Циклическое переключение разрядов индикатора
            // Паттерн W_DigitronCS_Out перемещает активный "ноль" по нужным позициям.
            W_DigitronCS_Out <= { W_DigitronCS_Out[5:2],
                                  W_DigitronCS_Out[0],
                                  W_DigitronCS_Out[1] };

            // Если дошли до "лишнего" промежуточного состояния,
            // возвращаемся к стартовому (используем только две позиции).
            if (W_DigitronCS_Out == 6'b11_1100)
                W_DigitronCS_Out <= 6'b11_1110;

            // Выбор, какую цифру показывать в текущем разряде:
            //  - когда активна позиция 6'b11_1110 — отображаем младший полубайт
            //  - когда активна позиция 6'b11_1101 — старший полубайт
            case (W_DigitronCS_Out)
                6'b11_1110: SingleNum <= Result[3:0];   // младшая цифра (единицы)
                6'b11_1101: SingleNum <= Result[7:4];   // старшая цифра (десятки)
                default:    SingleNum <= 4'd0;
            endcase

            // Декодирование цифры в шаблон сегментов
            case (SingleNum)
                4'd0:  W_Digitron_Out <= _0;
                4'd1:  W_Digitron_Out <= _1;
                4'd2:  W_Digitron_Out <= _2;
                4'd3:  W_Digitron_Out <= _3;
                4'd4:  W_Digitron_Out <= _4;
                4'd5:  W_Digitron_Out <= _5;
                4'd6:  W_Digitron_Out <= _6;
                4'd7:  W_Digitron_Out <= _7;
                4'd8:  W_Digitron_Out <= _8;
                4'd9:  W_Digitron_Out <= _9;
                default: W_Digitron_Out <= 8'b1111_1111; // все сегменты выкл.
            endcase
        end
        else begin
            Count <= Count + 1'b1;    // продолжаем считать до Timex
        end
    end

    // Связь внутренних регистров с внешними выводами
    assign Digitron_Out    = W_Digitron_Out;
    assign DigitronCS_Out  = W_DigitronCS_Out;

endmodule
