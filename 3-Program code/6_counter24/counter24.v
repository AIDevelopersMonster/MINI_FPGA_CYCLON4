// -----------------------------------------------------------------------------
//  Module Name : counter24
//  Project     : MINI_FPGA (Cyclone IV)
//  File        : counter24.v
//  Function    : 24-ричный счётчик с выводом значения на шестизначный
//                семисегментный индикатор (Digitron).
//                Счётчик реализован во внешнем модуле Accumulator_module,
//                а текущий результат передаётся в модуль динамической индикации
//                Digitron_NumDisplay_module.
//  Author      : (your name / nickname)
//  Date        : (yyyy-mm-dd)
// -----------------------------------------------------------------------------
//  Порты:
//      CLK             - тактовый сигнал платы FPGA
//      RSTn (SW0)      - асинхронный сброс, активный уровень низкий (0)
//      Digitron_Out    - шина сегментов 7-сегментного индикатора (a..g + dp)
//      DigitronCS_Out  - шина выбора разрядов индикатора (чип-select на 6 цифр)
// -----------------------------------------------------------------------------
//  Примечание:
//      - Логика счётчика (0..23 или другой диапазон) описана в Accumulator_module.
//      - Логика динамического мультиплексирования индикаторов —
//        в Digitron_NumDisplay_module.
//      - Данный верхний модуль только связывает оба блока и выводит их порты
//        на внешний мир.
// -----------------------------------------------------------------------------

module counter24
(
    CLK, RSTn, Digitron_Out, DigitronCS_Out
);

    input       CLK;                // input  - системный тактовый сигнал
    input       RSTn;               // input  - SW0, общий сброс (активный 0)

    output [7:0]Digitron_Out;       // output - линии сегментов индикатора
    output [5:0]DigitronCS_Out;     // output - выбор разряда (6 цифр)

    wire [7:0]Result;               // текущее значение счётчика (0..23 / 0..99 и т.п.)

    // -------------------------------------------------------------------------
    //  U1 : Accumulator_module
    //  Функция:
    //      - реализует сам счётчик (24-ричный / модуль 24);
    //      - по тактовому сигналу увеличивает значение или обнуляет при сбросе;
    //      - выдаёт результат как 8-битное число Result.
    // -------------------------------------------------------------------------
    Accumulator_module U1
    (
        .CLK   ( CLK   ),   // input        - системный тактовый сигнал
        .RSTn  ( RSTn  ),   // input        - общий сброс (активный 0)
        .Result( Result )    // output [7:0] - текущее значение счётчика (к U2)
    );

    // -------------------------------------------------------------------------
    //  U2 : Digitron_NumDisplay_module
    //  Функция:
    //      - принимает 8-битное значение Result;
    //      - формирует шаблон сегментов Digitron_Out;
    //      - динамически опрашивает разряды через DigitronCS_Out
    //        для отображения числа на 7-сегментных индикаторах.
    // -------------------------------------------------------------------------
    Digitron_NumDisplay_module U2
    (
        .CLK           ( CLK           ),  // input        - тактовый сигнал для мультиплексирования
        .Result        ( Result        ),  // input [7:0]  - значение счётчика от U1
        .Digitron_Out  ( Digitron_Out  ),  // output [7:0] - сегменты индикатора (к top)
        .DigitronCS_Out( DigitronCS_Out)   // output [5:0] - выбор разряда (к top)
    );

endmodule
