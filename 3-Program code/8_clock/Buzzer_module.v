//  Project   : MINI_FPGA_CYCLONE4
//  Title     : Buzzer_module – звуковая индикация хода времени
//  File      : Buzzer_module.v
//  Author    : 
//  Description :
//      Модуль формирует звуковые сигналы (пищалку) для цифровых часов:
//        - короткие «тики» перед наступлением нового часа;
//        - сигнал «ровно час» в момент 00:00.
//
//      Логика работы:
//        * При времени 59'50"–59'59" (Min = 59, SecH = 5) –
//          каждую секунду включается прерывистый сигнал частотой ~500 Гц
//          (на чётных SecL – звучит «di», на нечётных – пауза).
//        * При времени 00'00" – подаётся сигнал частотой ~1 кГц («da»).
//        * В остальное время выход находится в нерабочем состоянии
//          (для конкретной платы это может означать «тихий» уровень,
//           в зависимости от схемы подключения буззера).
//
//      Предположение: тактовая частота CLK = 50 МГц.
//      Для генерации частоты используется счётчик и сравнение с порогом:
//        Di = 50_000  -> ~500 Гц,
//        Da = 25_000  -> ~1 кГц.
//=======================================================

module Buzzer_module
(
	CLK, RSTn, SecL, SecH, MinL, MinH, Buzzer_Out
);	
	//------------------------------
	// Входы
	//------------------------------
	 input CLK;              // Системный тактовый сигнал (например, 50 МГц)
	 input RSTn;             // Глобальный сброс (в данном модуле явно не используется)
	 input [3:0]SecL;        // Секунды: младший BCD-разряд
	 input [3:0]SecH;        // Секунды: старший BCD-разряд
	 input [3:0]MinL;        // Минуты: младший BCD-разряд
	 input [3:0]MinH;        // Минуты: старший BCD-разряд

	//------------------------------
	// Выход
	//------------------------------
	 output Buzzer_Out;      // Управление пьезопищалкой

	//------------------------------
	// Параметры генератора частоты
	// Для CLK = 50 МГц:
	//   период сигнала = 2 * Pulse_x / 50e6
	//   Di = 50 000  -> 2 * 50 000 / 50e6 = 0,002 c  -> 500 Гц
	//   Da = 25 000  -> 2 * 25 000 / 50e6 = 0,001 c  -> 1 кГц
	//------------------------------
	 parameter Di = 16'd50_000;	// Порог для частоты ~500 Гц («di»)
	 parameter Da = 15'd25_000; // Порог для частоты ~1 кГц («da»)

    reg [22:0]Count;           // Счётчик тактов для формирования частоты
    reg [22:0]Pulse_x;         // Текущий выбранный период (Di / Da или «тишина»)
	 reg W_buzzer;             // Внутренний сигнал на буззер (квадратный меандр)
	
	//--------------------------------------------------
	// Формирование режима работы буззера по текущему времени
	//   - в интервале 59'50"–59'59" – прерывистый 500 Гц;
	//   - в момент 00'00" – непрерывный 1 кГц;
	//   - иначе – буззер выключен.
	//--------------------------------------------------
	always @( posedge CLK )
		begin
			// Время 59'50"–59'59": MinH = 5, MinL = 9, SecH = 5
			if( MinH == 'd5 && MinL == 'd9 && SecH == 'd5 )		
				begin
					// На чётных SecL – «ди» (500 Гц), на нечётных – пауза
					if( (SecL % 2) == 0)		
						Pulse_x <= Di;		// Включить 500 Гц
					else
						Pulse_x <= 20000;   // «Фиктивное» значение – буззер будет выключен
				end
			// Время 00'00": MinH = 0, MinL = 0, SecH = 0, SecL = 0
			else if( MinH == 0 && MinL == 0 && SecH == 0 && SecL == 0 )
				Pulse_x <= Da;		        // Включить 1 кГц
			else
				// Во все прочие моменты буззер выключен
				Pulse_x <= 20000;           // Значение, отличное от Di/Da – генератор остановлен
		end
	
   //--------------------------------------------------
   // Генератор квадратного сигнала для буззера
   //   - при Pulse_x = Di или Da – считаем до Pulse_x и инвертируем W_buzzer;
   //   - при других значениях Pulse_x – W_buzzer принудительно в «тихий» уровень.
   //--------------------------------------------------
   always @ ( posedge CLK )
		begin
			if( (Pulse_x == Di) | (Pulse_x == Da) )
				begin
					if( Count == Pulse_x )
						begin
							Count     <= 23'd0;
							W_buzzer  <= ~W_buzzer;  // Инверсия -> формирование меандра
						end
					else 
						Count <= Count + 1'b1;
				end
			else 
				begin
					// Режим «буззер выключен»
					W_buzzer <= 1'b1;       // Конкретный уровень зависит от схемы (часто активный 0)
					Count    <= 23'd0;
				end				
		end	
		
	// Передача внутреннего сигнала на вывод модуля
	assign Buzzer_Out = W_buzzer;
	
endmodule
