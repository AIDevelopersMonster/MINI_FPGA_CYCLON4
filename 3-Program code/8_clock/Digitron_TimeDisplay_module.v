//=======================================================
//  Project   : MINI_FPGA_CYCLONE4
//  Title     : Digitron_TimeDisplay_module – индикация времени и дня недели
//  File      : Digitron_TimeDisplay_module.v
//  Author    : 
//  Description :
//      Модуль управления 6-разрядным семисегментным индикатором (Digitron)
//      для отображения текущего времени и номера дня недели.
//
//      Режимы работы:
//        * Пока DispWeek_n = 0  ИЛИ AdjtWeek = 1:
//            – на младшем разряде (крайний справа) показывается номер дня недели;
//            – остальные разряды гаснут (через маску CS).
//        * В противном случае – отображается текущее время HH:MM:SS
//          с помощью динамического (временного) мультиплексирования.
//
//      Формат входных данных (BCD):
//        SecL / SecH   – секунды (единицы / десятки);
//        MinL / MinH   – минуты  (единицы / десятки);
//        HourL / HourH – часы    (единицы / десятки);
//        Week          – номер дня недели (1..7).
//
//      Управление индикатором:
//        Digitron_Out    – шаблон сегментов a–g, dp (активные уровни зависят от схемы);
//        DigitronCS_Out  – линии выбора разряда (6 разрядов, обычно активный 0).
//
//=======================================================

module Digitron_TimeDisplay_module
(
	CLK, RSTn, DispWeek_n, AdjtWeek, Digitron_Out, DigitronCS_Out,
	SecL, SecH, MinL, MinH, HourL, HourH, Week
);
	//------------------------------
	// Входные сигналы
	//------------------------------
	 input CLK;                 // Системный тактовый сигнал
	 input RSTn;                // Глобальный сброс (в данном модуле явно не используется)
	 input DispWeek_n;          // Пока = 0 – отображать день недели
	 input AdjtWeek;            // Режим корректировки дня недели (также принудительно показывает Week)

	 input [3:0]SecL;	        // Секунды: младший BCD-разряд
	 input [3:0]SecH;           // Секунды: старший BCD-разряд
	 input [3:0]MinL;	        // Минуты: младший BCD-разряд
	 input [3:0]MinH;           // Минуты: старший BCD-разряд
	 input [3:0]HourL;	        // Часы:   младший BCD-разряд
	 input [3:0]HourH;          // Часы:   старший BCD-разряд
	 input [3:0]Week;           // День недели: 1..7 (BCD)

	//------------------------------
	// Выходные сигналы на индикатор
	//------------------------------
	 output [7:0]Digitron_Out;      // Сегменты (a–g, dp)
	 output [5:0]DigitronCS_Out;    // Управление 6-ю разрядами индикатора

    //------------------------------
    // Внутренние регистры
    //------------------------------
    parameter T100MS = 16'd200;     // Интервал переключения разрядов (подбор экспериментально)
	 reg [7:0]Count;                // Счётчик для сканирования разрядов
	 reg [3:0]SingleNum;            // Текущее отображаемое число (один BCD-разряд)
	 reg [7:0]W_Digitron_Out;       // Регистровая версия шаблона сегментов
	 reg [7:0]W_DigitronCS_Out;     // Регистровая версия управления разрядами

    // Шаблоны сегментов для цифр 0–9 и отдельного варианта для дня недели 7
    // Формат: {dp, g, f, e, d, c, b, a} (зависит от конкретной платы)
    parameter _0  = 8'b0011_1111,
			 	  _1  = 8'b0000_0110,
			 	  _2  = 8'b0101_1011,
			 	  _3  = 8'b0100_1111,
			 	  _4  = 8'b0110_0110,
			 	  _5  = 8'b0110_1101,
			 	  _6  = 8'b0111_1101,
			 	  _7  = 8'b0000_0111,
			 	  _8  = 8'b0111_1111,
				  _9  = 8'b0110_1111,
				  _Ri = 8'b0111_1111;   // Спец. шаблон для Week=7 (например, «日» или «8»)

	//----------------------------------------
	// Основной процесс: выбор режима индикации и
	// динамическое мультиплексирование разрядов
	//----------------------------------------
	always @ ( posedge CLK )
		begin
			//--------------------------------------------------
			// Режим отображения дня недели:
			//   – активируется, если DispWeek_n = 0
			//     или включён режим AdjtWeek (коррекция недели)
			//   – используется только один разряд (правый)
			//--------------------------------------------------
			if( (DispWeek_n == 0) || (AdjtWeek == 1) )
				begin
					// Включен только младший разряд (шаблон CS зависит от схемы,
					// здесь: 6'b11_1110 – активен один разряд)
					W_DigitronCS_Out = 6'b11_1110;
					SingleNum        = Week;
					
					// Кодируем номер дня недели в семисегментный шаблон
					case( SingleNum )
						'd0:  W_Digitron_Out = _0;
						'd1:  W_Digitron_Out = _1;
						'd2:  W_Digitron_Out = _2;
						'd3:  W_Digitron_Out = _3;
						'd4:  W_Digitron_Out = _4;
						'd5:  W_Digitron_Out = _5;
						'd6:  W_Digitron_Out = _6;
						'd7:  W_Digitron_Out = _Ri;   // Отдельный образ цифры/символа для «7»
					endcase
				end
			//--------------------------------------------------
			// Режим отображения времени HH:MM:SS:
			//   – по достижении порога T100MS переключаем разряд
			//   – поочерёдно выводим SecL, SecH, MinL, MinH, HourL, HourH
			//--------------------------------------------------
			else if( Count == T100MS )
				begin
					// Обнуляем счётчик интервала
					Count <= 23'd0;

					// Циклическое сдвигание маски выборки разряда:
					// {b0, b5..b1} – «переключение» активного разряда по кругу
					W_DigitronCS_Out = { W_DigitronCS_Out[0], W_DigitronCS_Out[5:1] };

					// Если все биты "съехали в ноль" – принудительно включаем первый разряд
					if( W_DigitronCS_Out == 6'd0 ) 
						W_DigitronCS_Out = 6'b11_1110;
 
					// В зависимости от активного разряда выбираем,
					// какой BCD-разряд времени сейчас отображать
					case( W_DigitronCS_Out )
						6'b11_1110: SingleNum = SecL;   // Младшие секунды
						6'b11_1101: SingleNum = SecH;   // Старшие секунды
						6'b11_1011: SingleNum = MinL;   // Младшие минуты
						6'b11_0111: SingleNum = MinH;   // Старшие минуты
						6'b10_1111: SingleNum = HourL;  // Младшие часы
						6'b01_1111: SingleNum = HourH;  // Старшие часы
					endcase
 
					// Преобразуем выбранный BCD-разряд в семисегментный шаблон
					case( SingleNum )
						'd0:  W_Digitron_Out = _0;
						'd1:  W_Digitron_Out = _1;
						'd2:  W_Digitron_Out = _2;
						'd3:  W_Digitron_Out = _3;
						'd4:  W_Digitron_Out = _4;
						'd5:  W_Digitron_Out = _5;
						'd6:  W_Digitron_Out = _6;
						'd7:  W_Digitron_Out = _7;
						'd8:  W_Digitron_Out = _8;
						'd9:  W_Digitron_Out = _9;
					endcase
				end
			//--------------------------------------------------
			// Пока не накоплен интервал T100MS – просто считаем
			//--------------------------------------------------
			else
				Count <= Count + 1'b1;
	end
		
	// Передача регистровых значений на выходы модуля
	assign Digitron_Out    = W_Digitron_Out;
	assign DigitronCS_Out  = W_DigitronCS_Out;
	 
endmodule
