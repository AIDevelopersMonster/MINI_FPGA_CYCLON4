//=======================================================
//  Project   : MINI_FPGA_CYCLONE4
//  Title     : TimeKeeper_module – генератор и хранитель времени
//  File      : TimeKeeper_module.v
//  Author    : 
//  Description :
//      Модуль формирует «ядро» часов:
//        - делит тактовый сигнал CLK до частоты 1 Гц;
//        - считает секунды, минуты, часы и день недели;
//        - обеспечивает режимы подстройки дня недели, часов и минут
//          с помощью входных сигналов AdjtWeek, AdjtHour, AdjtMin;
//        - выдаёт время в формате BCD по разрядам:
//
//          SecL / SecH   – секунды (единицы / десятки),
//          MinL / MinH   – минуты  (единицы / десятки),
//          HourL / HourH – часы    (единицы / десятки),
//          Week          – номер дня недели (1..7).
//
//      Принято, что:
//        * RSTn – асинхронный активный низкий сброс;
//        * частота системного тактового сигнала CLK = 50 МГц;
//        * делитель формирует сигнал CLK_1HZ с периодом 1 с
//          (т.е. частота 1 Гц, каждый фронт – одна секунда).
//=======================================================

module TimeKeeper_module
(
	CLK, RSTn, AdjtWeek, AdjtHour, AdjtMin,
	SecL, SecH, MinL, MinH, HourL, HourH, Week
);
	//------------------------------
	// Входные сигналы
	//------------------------------
	 input CLK;            // Системный тактовый сигнал (например, 50 МГц)
	 input RSTn;           // Глобальный сброс, активный низким уровнем
	 input AdjtWeek;       // Режим корректировки дня недели
	 input AdjtHour;       // Режим корректировки часов
	 input AdjtMin;        // Режим корректировки минут

	//------------------------------
	// Выходные сигналы – BCD-разряды времени
	//------------------------------
	 output reg [3:0]SecL;   // Секунды: младший разряд (0–9)
	 output reg [3:0]SecH;   // Секунды: старший разряд (0–5)
	 output reg [3:0]MinL;   // Минуты: младший разряд (0–9)
	 output reg [3:0]MinH;   // Минуты: старший разряд (0–5)
	 output reg [3:0]HourL;  // Часы:   младший разряд (0–9)
	 output reg [3:0]HourH;  // Часы:   старший разряд (0–2)
	 output reg [3:0]Week;   // День недели: 1..7 (BCD)

	//------------------------------
	// Делитель частоты до 1 Гц
	//------------------------------
	 reg CLK_1HZ = 0;        // Локальный «секундный» такт (1 Гц)
	 reg [24:0]Count;        // Счётчик тактов системной частоты

	 // Для CLK = 50 МГц:
	 //  - период одного такта = 20 нс;
	 //  - 25 000 000 тактов = 0,5 с;
	 //  - инверсия CLK_1HZ каждые 25 000 000 тактов даёт период 1 с.
	 parameter T1HZ = 25'd25_000_000;	// half-period для формирования 1 Гц

	// Делитель: формируем CLK_1HZ
	always @ ( posedge CLK )
		begin 
			if( Count == T1HZ - 25'b1 )
				begin
					Count    <= 0;
					CLK_1HZ  <= ~CLK_1HZ;  // инвертируем раз в T1HZ тактов
				end
			else
				Count <= Count + 1;
		end
		
	//------------------------------
	// Основной счётчик времени
	// – работает от «секундного» такта CLK_1HZ
	// – асинхронный сброс по RSTn (активный 0)
	// – приоритет: Week > Hour > Min > счёт секунд
	//------------------------------
	always @ ( posedge CLK_1HZ or negedge RSTn )
		begin
			//----------------------------------
			// Асинхронный сброс – стартовое время:
			//  00:00:00, день недели = 1
			//----------------------------------
			if( !RSTn )
				begin 
					SecL  <= 0;
					SecH  <= 0;
					MinL  <= 0;
					MinH  <= 0;
					HourL <= 0;
					HourH <= 0;
					Week  <= 1;
				end
			else
				begin
					//----------------------------------
					// Режим корректировки дня недели
					//----------------------------------
					if( AdjtWeek == 1 )		// Пока AdjtWeek = 1 – «листать» день недели
						begin  
							if( Week == 'd7 )   // После 7-го дня снова 1
								Week <= 1;
							else
								Week <= Week + 1;
						end
					//----------------------------------
					// Режим корректировки часов
					//----------------------------------
					else if( AdjtHour == 1 )
						begin 
							// Увеличиваем часы по BCD с контролем 23 -> 00
							if( HourL == 'd9 )
								begin
									HourL <= 0;
									HourH <= HourH + 1;
								end
							else
								begin
									// Специальный случай: 23 -> 00
									if( HourH == 'd2 && HourL == 'd3 )
										begin
											HourL <= 0;
											HourH <= 0;
										end
									else
										HourL <= HourL + 1;
								end
						end
					//----------------------------------
					// Режим корректировки минут
					//----------------------------------
					else if( AdjtMin == 1 )
						begin
							// Увеличиваем минуты по BCD с контролем 59 -> 00
							if( MinL == 'd9 )
								begin
									MinL <= 0;
									if( MinH == 'd5 )
										MinH <= 0;
									else
										MinH <= MinH + 1;
								end					
							else 
								MinL <= MinL + 1;	
						end
					//----------------------------------
					// Обычный режим – часы «идут» сами
					//----------------------------------
					else if( SecL == 'd9 )	// Рост и перенос младшего разряда секунд
						begin 
							SecL <= 0;

							// Перенос в десятки секунд
							if( SecH == 'd5 )
								begin
									SecH <= 0;

									// Перенос в минуты
									if( MinL == 'd9 )
										begin
											MinL <= 0;
											if( MinH == 'd5 )
												begin
													MinH <= 0;

													// Перенос в часы
													if( HourL == 'd9 )
														begin
															HourL <= 0;
															HourH <= HourH + 1;
														end
													// Специальный случай: 23:59:59 -> 00:00:00 + смена дня недели
													else if( HourH == 'd2 && HourL == 'd3 )
														begin
															HourL <= 0;
															HourH <= 0;
															if( Week == 7 )													 
																Week <= 1;	// после 7 снова 1
															else
																Week <= Week + 1;															
														end
													else
														HourL <= HourL + 1;
												end
											else
												MinH <= MinH + 1;
										end
									else
										MinL <= MinL + 1;
								end
							else
								SecH <= SecH + 1;
						end
					else
						// Увеличиваем младший разряд секунд, пока он < 9
						SecL <= SecL + 1;
				end
		end

endmodule
