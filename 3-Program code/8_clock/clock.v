//=======================================================
//  Project   : MINI_FPGA_CYCLONE4
//  Title     : clock – верхний уровень многофункциональных часов
//  File      : clock.v
//  Author    : 
//  Description :
//      Верхний модуль цифровых часов для платы MINI_FPGA (Cyclone IV).
//      Функции:
//        - Подсчёт реального времени (часы / минуты / секунды + номер дня недели);
//        - Режим корректировки времени и дня недели с помощью переключателей;
//        - Отображение времени на 6-разрядном семисегментном индикаторе;
//        - Отображение дня недели по нажатию кнопки;
//        - Звуковой сигнал (например, по условию «ровный час»).
//
//      Связь с элементами платы:
//        * CLK        – тактовый генератор от внешнего кварца (50 МГц);
//        * KEY0 (RSTn)      – асинхронный сброс часов (активный 0);
//        * KEY1 (DispWeek_n) – при нажатии отображает день недели вместо времени;
//        * SW0 (AdjtWeek)    – режим корректировки дня недели;
//        * SW1 (AdjtMin)     – режим корректировки минут;
//        * SW2 (AdjtHour)    – режим корректировки часов.
//
//      В этом модуле производится только стыковка трёх блоков:
//        - TimeKeeper_module           – формирование счётчиков времени;
//        - Digitron_TimeDisplay_module – мультиплексирование и вывод на индикатор;
//        - Buzzer_module               – формирование сигнала пищалки по времени.
//=======================================================

module clock
(
	CLK, RSTn, DispWeek_n, AdjtWeek, AdjtHour, AdjtMin,
	Buzzer_Out, Digitron_Out, DigitronCS_Out
);
	//------------------------------
	// Входные сигналы
	//------------------------------
	 input CLK;             // Системный тактовый сигнал (например, 50 МГц)
	 input RSTn;            // KEY0: глобальный сброс (активный низкий уровень)
	 input DispWeek_n;      // KEY1: при нажатии – вывести на индикатор номер дня недели
	 input AdjtWeek;        // SW0: режим регулировки дня недели
	 input AdjtHour;        // SW2: режим регулировки часа
	 input AdjtMin;         // SW1: режим регулировки минут

	//------------------------------
	// Выходные сигналы
	//------------------------------
	 output Buzzer_Out;         // Выход на пищалку (звуковой сигнал, напр. каждый час)
	 output [7:0]Digitron_Out;  // Линии сегментов семисегментного индикатора (a–g, dp)
	 output [5:0]DigitronCS_Out;// Линии выбора разряда индикатора (6 разрядов)

	//------------------------------
	// Внутренние шины для времени
	// Представление в формате BCD:
	//   SecL, SecH  – единицы и десятки секунд
	//   MinL, MinH  – единицы и десятки минут
	//   HourL,HourH – единицы и десятки часов
	//   Week        – номер дня недели (1..7)
	//------------------------------
	 wire [3:0]SecL;		
	 wire [3:0]SecH;
	 wire [3:0]MinL;		
	 wire [3:0]MinH;
	 wire [3:0]HourL;		
	 wire [3:0]HourH;
	 wire [3:0]Week;	

	//--------------------------------------------------
	// U1: Блок формирования времени
	// TimeKeeper_module
	//   - Деление системного такта до 1 Гц
	//   - Счётчик секунд / минут / часов
	//   - Счётчик дня недели
	//   - Реагирует на сигналы корректировки
	//--------------------------------------------------
	TimeKeeper_module U1
	(
		.CLK       ( CLK ) ,
		.RSTn      ( RSTn ) ,	
		.AdjtWeek  ( AdjtWeek ) ,	// Режим корректировки дня недели
		.AdjtHour  ( AdjtHour ) ,	// Режим корректировки часа	
		.AdjtMin   ( AdjtMin ) ,	// Режим корректировки минут	
		.SecL      ( SecL ) ,	    // Младший разряд секунд (BCD)
		.SecH      ( SecH ) ,	    // Старший разряд секунд (BCD)
		.MinL      ( MinL ) ,	    // Младший разряд минут (BCD)
		.MinH      ( MinH ) ,	    // Старший разряд минут (BCD)
		.HourL     ( HourL ) ,      // Младший разряд часов (BCD)
		.HourH     ( HourH ) ,	    // Старший разряд часов (BCD)
		.Week      ( Week )	        // Номер дня недели (BCD)
	);
	
	//--------------------------------------------------
	// U2: Блок отображения времени/дня недели
	// Digitron_TimeDisplay_module
	//   - Управление динамической индикацией 6-разрядного
	//     семисегментного индикатора;
	//   - Переключение между показом времени и днём недели
	//     по сигналу DispWeek_n.
	//--------------------------------------------------
	Digitron_TimeDisplay_module U2
	(
		.CLK            ( CLK ) ,	
		.RSTn           ( RSTn ) ,	
		.DispWeek_n     ( DispWeek_n ) ,  // Кнопка отображения дня недели
		.AdjtWeek       ( AdjtWeek ) ,	   // Для индикатора можно подсветить корректируемый день
		.Digitron_Out   ( Digitron_Out ) ,    // Линии сегментов на индикатор
		.DigitronCS_Out ( DigitronCS_Out ) ,  // Линии выбора разряда
		.SecL           ( SecL ) ,	       // Секунды от U1
		.SecH           ( SecH ) ,
		.MinL           ( MinL ) ,
		.MinH           ( MinH ) ,
		.HourL          ( HourL ) ,
		.HourH          ( HourH ) ,
		.Week           ( Week )
	);

	//--------------------------------------------------
	// U3: Блок звуковой сигнализации
	// Buzzer_module
	//   - Формирует звуковой сигнал на выход Buzzer_Out
	//     в зависимости от текущего времени (Sec/Min).
	//   - Например, можно реализовать «бой часов» раз в час.
	//--------------------------------------------------
	Buzzer_module U3
	(
		.CLK        ( CLK ) ,	
		.RSTn       ( RSTn ) ,	
		.SecL       ( SecL ) ,	// Текущее значение секунд (BCD)
		.SecH       ( SecH ) ,
		.MinL       ( MinL ) ,	// Текущее значение минут (BCD)
		.MinH       ( MinH ) ,
		.Buzzer_Out ( Buzzer_Out )	// Выход на пьезопищалку 	
	);
	
endmodule
