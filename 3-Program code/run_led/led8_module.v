//==============================================================
// Module: led8_module   (run_led)
// Function: 8-битный бегущий светодиод с задержкой ~100 мс
// Hardware Note:
//   - Линия RSTn подключена к ползунковому переключателю SW0.
//   - Активный сброс — низким уровнем.
//   - SW0 вниз  = RSTn = 0  → модуль в сбросе, горит только LED0.
//   - SW0 вверх = RSTn = 1  → модуль работает, огонёк бежит.
//   - По правилам схемотехники SW0 должен иметь подтяжку к +3.3V,
//     но на плате MINI_FPGA полноценная цепь reset не реализована,
//     поэтому положение переключателя критически влияет на поведение.
//==============================================================

module led8_module
(
    CLK,        // Системный тактовый сигнал (обычно 50 MHz)
    RSTn,       // Активный-низкий сброс (подключен к SW0)
    LED_Out     // 8 выходов на светодиоды
);

    input CLK;
    input RSTn;           // Важно: SW0 вниз = RESET
    output [7:0] LED_Out;

    // Период задержки 100 мс при частоте CLK = 50 MHz
    parameter T100MS = 23'd5_000_000;      

    reg [22:0] Count;       // Счетчик задержки
    reg [7:0]  rLED_Out;    // Текущее состояние светодиодов
	 
    always @ (posedge CLK or negedge RSTn)
        if (!RSTn) begin
            // ---
            // Состояние при сбросе (SW0 внизу):
            // - rLED_Out фиксируется в 0000_0001
            // - Count обнуляется
            // - Огонёк не бежит
            // ---
            Count     <= 23'd0;
            rLED_Out  <= 8'b0000_0001;
        end
        else if (Count == T100MS - 1'b1) begin
            // Каждые T100MS происходит циклический сдвиг
            Count <= 23'd0;

            if (rLED_Out == 8'b0000_0000)
                rLED_Out <= 8'b0000_0001;
            else
                // Циклический сдвиг вправо (бегущий огонь)
                rLED_Out <= {rLED_Out[0], rLED_Out[7:1]};
        end
        else begin
            Count <= Count + 1'b1; // счёт задержки
        end

    assign LED_Out = rLED_Out;

endmodule
