//==========================================================================
// Module: run_led
// Function: Верхнеуровневый модуль для запуска бегущего светодиода
//
// Hardware Notes:
//   - Вход RSTn подключён к ползунковому переключателю SW0.
//   - Активный сброс — низким уровнем.
//   - SW0 вниз  = RSTn = 0 → модуль в состоянии RESET, горит только LED0.
//   - SW0 вверх = RSTn = 1 → нормальная работа, огонёк бежит.
//   - На плате MINI_FPGA отсутствует полноценная схема POR/reset,
//     поэтому по умолчанию все ползунки должны быть в положении “вверх” (3.3V).
//==========================================================================

module run_led
(
    CLK,        // Системный тактовый сигнал (50 МГц)
    RSTn,       // Активный-низкий сброс, SW0: вниз=RESET, вверх=RUN
    LED_Out     // 8-битная шина на светодиоды
);

    input  CLK;          // Подача тактового сигнала
    input  RSTn;         // SW0: 0 = RESET, 1 = RUN
    output [7:0] LED_Out; // Выход на светодиоды (вверх уровня проекта)

    //==============================================================
    // Экземпляр функционального модуля бегущего огонька
    //==============================================================
    led8_module U1
    (
        .CLK     (CLK),       // input  — передаём системный такт
        .RSTn    (RSTn),      // input  — сброс с SW0 (активный низкий)
        .LED_Out (LED_Out)    // output — 8-битный результат наружу
    );

endmodule
